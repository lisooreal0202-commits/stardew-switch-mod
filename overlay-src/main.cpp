// One-hit kill.
//
// GameLocation.damageMonster(Rectangle, int minDamage, int maxDamage, ...) is
// the single entry every monster damage goes through. Its first two stores
// copy the damage range out of the argument registers:
//
//   0x14EA504  mov w22, w4     ; maxDamage
//   0x14EA508  mov w21, w3     ; minDamage
//   ...
//   0x14EA580  add w8, w22, #1 ; Game1.random.Next(min, max + 1)
//
// Replacing both with an immediate makes every hit roll 9999 without touching
// any monster object, and without a code cave.
constexpr u64 kDmgMaxOff = 0x14EA504ULL;
constexpr u64 kDmgMinOff = 0x14EA508ULL;
constexpr u32 kDmgMaxOrig = 0x2A0403F6u;   // mov w22, w4
constexpr u32 kDmgMinOrig = 0x2A0303F5u;   // mov w21, w3
constexpr u32 kDmgMaxHit  = 0x5284E1F6u;   // mov w22, #9999
constexpr u32 kDmgMinHit  = 0x5284E1F5u;   // mov w21, #9999
bool gOneHitKill = false;

void setOneHitKill(bool on, bool force) {
    if (!force && on == gOneHitKill) return;
    const u32 maxWord = on ? kDmgMaxHit : kDmgMaxOrig;
    const u32 minWord = on ? kDmgMinHit : kDmgMinOrig;
    if (!poke(kDmgMaxOff, &maxWord, 4) || !poke(kDmgMinOff, &minWord, 4)) {
        logError("one-hit patch failed (on=%d)", (int)on);
        setStatus("补丁写入失败");
        return;
    }
    gOneHitKill = on;
    // Every write this overlay makes to the damage site is logged with its
    // address, because "the site is already patched in a process that just
    // started" is only decidable if the log can show that no write of ours
    // came before it.  Same address and no line above it means the page came
    // in patched from somewhere else; a line above it means it was us.
    logLine("one-hit wrote %08X/%08X at %016llX", (unsigned)maxWord,
            (unsigned)minWord, (unsigned long long)(gNsoBase + kDmgMaxOff));
    logLine("one-hit kill -> %s", on ? "ON" : "OFF");
    setStatus(on ? "一击必杀 已开" : "一击必杀 已关");
}

// Auto-watering.
//
// HoeDirt.dayUpdate ends with:
//
//   0x1B1C68C  ldr x8, [x19, #0x38]   ; state (a NetInt)
//   0x1B1C690  mov w1, wzr            ; value 0 = dry
//   0x1B1C6A8  blr x10                ; state.set_Value(0)
//
// The growth call earlier in the same method reads state.Value, so leaving the
// soil at 1 makes every tilled tile count as watered and crops advance a stage
// per day without the watering can.
constexpr u64 kWaterOff  = 0x1B1C690ULL;
constexpr u32 kWaterOrig = 0x2A1F03E1u;   // mov w1, wzr
constexpr u32 kWaterOn   = 0x52800021u;   // mov w1, #1
bool gAutoWater = false;

void setAutoWater(bool on, bool force) {
    if (!force && on == gAutoWater) return;
    const u32 word = on ? kWaterOn : kWaterOrig;
    if (!poke(kWaterOff, &word, 4)) {
        logError("auto-water patch failed (on=%d)", (int)on);
        setStatus("补丁写入失败");
        return;
    }
    gAutoWater = on;
    logLine("auto-water -> %s", on ? "ON" : "OFF");
    setStatus(on ? "自动浇水 已开" : "自动浇水 已关");
}

