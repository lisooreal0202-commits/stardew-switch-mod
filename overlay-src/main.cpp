// Toggle state, persisted alongside the item settings in sdv_items.cfg.
struct SdvConfig {
    bool oneHitKill = false;
    bool autoWater  = false;
    bool allRecipes = false;
    bool allCollections = false;
    // Enhancements taken over from the cheat file.  speed/gather are indices
    // into their level tables, so 0 means "original" for both.
    int  speed      = 0;
    bool autoFish   = false;
    bool stamina    = false;
    int  gather     = 0;
    bool gatherLock = false;
    bool waterCan   = false;
    // Fixed balance, 0 meaning "off".  The patch lives in .text and is gone
    // once the process exits, so this has to be re-applied on every menu open
    // or a 500,000 setting would silently last exactly one session.
    unsigned int money = 0;
};

SdvConfig gCfg;

// Called when the menu opens.  Silently does nothing if the game is not
// running yet -- the user may open the overlay before launching.
//
// It enforces both directions now, not just the "on" ones.  The old version
// returned early when every switch was off, which meant "off" was not a state
// anything ever applied: it was merely the absence of a patch.  One console
// turned out to have something else patching the damage site at process start,
// so the menu said 已关 while every hit still rolled 9999 -- and with nothing
// to write, the overlay could not correct it.  Writing the original word back
// costs two stores and makes the switches describe reality.
void applySavedConfig() {
    // Speed and auto-fish are NOT here any more: they are static code patches,
    // so they live in the cheat file and Atmosphère applies them at process
    // start.  Leaving them here would undo the cheat file the moment the menu
    // opens -- exactly the "menu says off, reality says patched" failure this
    // function was written to prevent, just pointing the other way.
    const bool anyOn = gCfg.oneHitKill || gCfg.autoWater ||
                       gCfg.allRecipes || gCfg.allCollections ||
                       gCfg.stamina ||
                       gCfg.gather != 0 || gCfg.gatherLock || gCfg.waterCan ||
                       gCfg.money != 0;
    if (!anyOn && !gOpen) {
        // Nothing to enforce and nothing connected: connecting just to look
        // would turn a quiet menu into "挂载失败" for anyone who opens the
        // overlay before launching the game.  Once a give has attached, the
        // call above is false and the enforcement below runs.
        return;
    }
    if (!attach()) return;
    setOneHitKill(gCfg.oneHitKill, true);
    setAutoWater(gCfg.autoWater, true);
    setAllRecipes(gCfg.allRecipes, true);
    setAllCollections(gCfg.allCollections, true);
    setGather(gCfg.gather, true);
    setStamina(gCfg.stamina, true);
    setGatherLock(gCfg.gatherLock, true);
    setWaterCan(gCfg.waterCan, true);
    // Money is a .text patch like the rest, so it evaporates with the process;
    // without this a 500,000 balance would survive exactly one session.  And
    // like the rest it has to be enforced in both directions -- a config that
    // says off while the accessor still branches into the stub is exactly the
    // lie the 已关 switches used to tell, so the original word goes back too.
    if (gCfg.money) {
        setMoney(gCfg.money);
    } else {
        u32 site = 0;
        if (peek(kMoneyInsn, &site, sizeof(site)) && site != kMoneyOrig)
            restoreMoney();
    }
    // Each setter leaves its own name in the subtitle; the menu open is not
    // about any one of them, so put the connection status back.
    setStatus("已连接");
    logLine("config enforced on menu open (one_hit=%d water=%d recipe=%d coll=%d "
            "speed=%d fish=%d stam=%d gather=%d lock=%d can=%d money=%u)",
            (int)gCfg.oneHitKill, (int)gCfg.autoWater,
            (int)gCfg.allRecipes, (int)gCfg.allCollections,
            gCfg.speed, (int)gCfg.autoFish, (int)gCfg.stamina,
            gCfg.gather, (int)gCfg.gatherLock, (int)gCfg.waterCan,
            (unsigned)gCfg.money);
    // After the patches are applied, never before: a config that says "on" is
    // *supposed* to disagree with memory until this function has finished.
    checkToggleConsistency();
}

// Unlock every crafting recipe.
//
// CraftingPage.GetRecipesToDisplay walks the full recipe table and keeps a key
// only when the player has learned it:
//
//   0x176E4DC  bl 0x1440570        ; Game1.get_player()
//   0x176E4E0  ldr x8, [x0, #0x1f8] ; player.craftingRecipes
//   0x176E4E4  ldr x0, [x8, #0x58]  ; inner Dictionary
//   0x176E4EC  bl 0x12D6F00         ; ContainsKey
//   0x176E4F0  tbz w0, #0, loop     ; <- skip when not learned
//   0x176E4FC  bl 0x9D40            ; list.Add(key)
//
// NOPing the branch lists every recipe. The dictionary itself is untouched, so
// the "+=" in craftItem still sees ContainsKey == false for an unlearned
// recipe and skips the bookkeeping instead of throwing on a missing key.
constexpr u64 kRecipeGateOff  = 0x176E4F0ULL;
constexpr u32 kRecipeGateOrig = 0x3607FE80u;   // tbz w0, #0, 0x176E4C0
constexpr u32 kRecipeGateNop  = 0xD503201Fu;
bool gAllRecipes = false;

// Write one 32-bit patch word, but only after checking that what is already
// there is either the pristine instruction or the patch itself.  These offsets
// come from one specific build (E7F845093E8CBC68); on any other build a stale
// offset would silently overwrite an unrelated instruction and take the
// console down.  Failing loudly in the log is strictly better than that.
bool patchWord(u64 off, u32 orig, u32 patched, bool on) {
    u32 cur = 0;
    if (!peek(off, &cur, sizeof(cur))) {
        logError("patch 0x%llX unreadable", (unsigned long long)off);
        return false;
    }
    if (cur != orig && cur != patched) {
        logError("patch 0x%llX has unexpected %08X, refusing", (unsigned long long)off, cur);
        return false;
    }
    const u32 word = on ? patched : orig;
    return poke(off, &word, sizeof(word));
}

void setAllRecipes(bool on, bool force) {
    if (!force && on == gAllRecipes) return;
    if (!patchWord(kRecipeGateOff, kRecipeGateOrig, kRecipeGateNop, on)) {
        logError("recipe patch failed (on=%d)", (int)on);
        setStatus("补丁写入失败");
        return;
    }
    gAllRecipes = on;
    logLine("all-recipes -> %s", on ? "ON" : "OFF");
    setStatus(on ? "配方 已开" : "配方 已关");
}

// Unlock the collections tab.
//
// CollectionsPage's constructor precomputes a "seen" flag per entry by asking
// the player's collection dictionaries:
//
//   0x175BE30  ldr x8, [x0, #0x6b0]   ; fishCaught
//   0x175BE3C  bl 0x12D7220           ; NetStringIntArrayDictionary.ContainsKey
//
//   0x175C24C  ldr x8, [x0, #0x698]   ; basicShipped
//   0x175C258  bl 0x12D6F00           ; Dictionary<string,int>.ContainsKey
//
//   0x175C354  ldr x8, [x0, #0x6a8]   ; recipesCooked
//   0x175C360  bl 0x12D6F00
//
//   0x175C378  ldr x8, [x0, #0x1f0]   ; cookingRecipes
//   0x175C384  bl 0x12D6F00
//
// The minerals and artifacts tabs never touch a dictionary -- they ask
// LibraryMuseum.HasDonatedArtifact(itemId), a static helper over
// netWorldState.MuseumPieces.  It is called twice from the same switch:
//
//   0x175BDCC  bl 0x166FAC0           ; Minerals  (mov w27, #2 right after)
//   0x175BEA0  bl 0x166FAC0           ; Artifacts (mov w27, #3 right after)
//
// Each call is replaced with "mov w0, #1" so every entry reads as collected;
// the following "and w8, w0, #1" then stores 1 into the drawShadow byte.
// The calls are patched individually rather than the callee itself, because
// all of them are shared with the rest of the game -- a global "always
// contains" would make craftItem's 'dict[name] += n' hit a missing key and
// throw, and a global "always donated" would tell the museum GUI that the
// player has nothing left to hand in.
struct CollectPatch { u64 off; u32 orig; };
constexpr CollectPatch kCollectSites[] = {
    { 0x175BE3CULL, 0x97EDECF9u },   // fishCaught
    { 0x175C258ULL, 0x97EDEB2Au },   // basicShipped
    { 0x175C360ULL, 0x97EDEAE8u },   // recipesCooked
    { 0x175C384ULL, 0x97EDEADFu },   // cookingRecipes
    { 0x175BDCCULL, 0x97FC4F3Du },   // Minerals  -> HasDonatedArtifact
    { 0x175BEA0ULL, 0x97FC4F08u },   // Artifacts -> HasDonatedArtifact
};
constexpr u32 kCollectTrue = 0x52800020u;   // mov w0, #1
bool gAllCollections = false;

void setAllCollections(bool on, bool force) {
    if (!force && on == gAllCollections) return;
    bool ok = true;
    for (const auto& site : kCollectSites) {
        if (!patchWord(site.off, site.orig, kCollectTrue, on)) {
            ok = false;
            logError("collect patch 0x%llX failed", (unsigned long long)site.off);
        }
    }
    if (!ok) { setStatus("补丁写入失败"); return; }
    gAllCollections = on;
    logLine("all-collections -> %s", on ? "ON" : "OFF");
    setStatus(on ? "收集品 已开" : "收集品 已关");
}

// ---------------------------------------------------------------------------
// Enhancements taken over from the dmnt cheat file.
//
// Every entry in that file is a group of words written into the game's text
// segment: a multiplier constant, a `mov w0, #60000` in front of a getter, or a
// nop over a branch.  dmnt applies them once, when the process starts, and the
// only way to undo one is the file's own "turn everything off" entry -- which is
// why flipping a switch there looked like it did nothing.
//
// Here each group is a table of {offset, original word, patched word}.  The
// original words are not guesses: they are exactly what the cheat file writes
// back in its own restore entry.  A word that matches neither means this is not
// the build the offsets came from, so the group refuses to write anything --
// the same read-compare-write discipline patchWord() uses, applied per group so
// a half-applied patch cannot happen.
//
// Everything the cheat file used to carry is now a patch applied from here --
// the last two holdouts were money and the clock, and both have a page of their
// own now.  The clock is the odd one: it writes Game1's static day/hour fields,
// which are save state rather than code, so poking it skips the day-boundary
// logic that grows crops and moves NPCs.  That is also why it stays out of the
// restore-all path: there is no original word to write back, only a calendar
// value nobody recorded.
struct WordPatch { u64 off; u32 orig; u32 patched; };

bool applyGroup(const WordPatch* sites, int n, bool on, const char* tag) {
    for (int i = 0; i < n; ++i) {
        u32 cur = 0;
        if (!peek(sites[i].off, &cur, sizeof(cur))) {
            logError("%s: site %d unreadable at %08llX", tag, i,
                     (unsigned long long)sites[i].off);
            return false;
        }
        if (cur != sites[i].orig && cur != sites[i].patched) {
            logError("%s: site %d has %08X (want %08X or %08X), refusing",
                     tag, i, (unsigned)cur, (unsigned)sites[i].orig,
                     (unsigned)sites[i].patched);
            return false;
        }
    }
    for (int i = 0; i < n; ++i) {
        const u32 word = on ? sites[i].patched : sites[i].orig;
        if (!poke(sites[i].off, &word, sizeof(word))) {
            // Put back whatever this call already wrote.  A half-applied group
            // is worse than an untouched one: the feature breaks in a way no
            // switch describes, and the next press refuses at the read gate
            // because the group is now neither orig nor patched.
            for (int j = i - 1; j >= 0; --j) {
                const u32 back = on ? sites[j].orig : sites[j].patched;
                poke(sites[j].off, &back, sizeof(back));
            }
            logError("%s: write %d failed at %08llX, rolled back %d",
                     tag, i, (unsigned long long)sites[i].off, i);
            return false;
        }
    }
    logLine("%s -> %s", tag, on ? "ON" : "OFF");
    return true;
}

// Walk speed.  The constant is a mov/movk pair, so switching levels has to write
