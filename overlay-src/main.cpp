// Money.  The official 1.6.15.13 cheat patches one instruction:
//
//   013B97F8  B9406800   ldr w0, [x0, #0x68]     <- the money accessor
//            529D4C00   movz w0, #60000          <- what the cheat writes
//
// The getter then reports a fixed amount, so the balance never goes down.
// One instruction can only hold a 16-bit immediate -- that is why the cheat
// file stops at 65535 and why this page used to stop there too.  Anything
// larger needs a second instruction, and there is no second word to spare at
// the accessor.
//
// So the accessor is pointed at a stub in the tail of .text instead.
//
// The stub is four words, not three, and the fourth one matters.  The function
// this sits in has a frame:
//
//   013B97E0  stp x29, x30, [sp, #-0x10]!    prologue, sp drops by 16
//   013B97E4  mov x29, sp
//   ...
//   013B97F8  ldr w0, [x0, #0x68]            <- the word being replaced
//   013B97FC  ldp x29, x30, [sp], #0x10      epilogue, sp comes back
//   013B9800  ret
//
// A stub that just did movz/movk/ret skipped that epilogue and returned with
// sp 16 bytes low, which corrupts the caller's stack on the very first money
// read.  That was build 14's crash.  The epilogue word is copied verbatim from
// the NSO, so the stub leaves the registers exactly as the original path did.
//
//   movz w0, #lo16
//   movk w0, #hi16, lsl 16
//   ldp x29, x30, [sp], #0x10
//   ret
//
// It sits just past the end of the item shell, in the padding between the end
// of .text and the next page boundary where the executable mapping stops.  It
// is written only after those sixteen bytes have been read and found zero (or
// found to be an earlier copy of our own stub), so a future layout change
// refuses the write rather than overwriting something live.
constexpr u64 kMoneyInsn  = 0x013B97F8;
constexpr u32 kMoneyOrig  = 0xB9406800;   // ldr w0, [x0, #0x68]

// Derived rather than typed in.  installShell() rewrites [kShellAddr,
// kShellAddr + kShellSize) every time it runs, so a literal stub address is a
// promise that the shell will never grow -- and it already did once (652 to
// 736 bytes).  Written as an offset from the shell's own end, the stub moves
// with the body instead of being erased by the next install.
constexpr u64 kMoneyCave  = sdv::kShellAddr + sdv::kShellSize + 0x10;
constexpr u32 kMoneyRet   = 0xD65F03C0;   // ret
constexpr u32 kMoneyPop   = 0xA8C17BFD;   // ldp x29, x30, [sp], #0x10
constexpr int kMoneyStub  = 4;            // words
constexpr u32 kMoneyMax   = 999999999;

// The r-x mapping runs to the next page boundary after .text, which is what
// the loader reserved; anything written past it would land in rodata and the
// guard below would be the only thing standing between us and a page fault
// on the read.
constexpr u64 kMoneyTextEnd = (sdv::kShellAddr + 0x1000) & ~(u64)0xFFF;
static_assert(kMoneyCave % 4 == 0, "money stub must be word aligned");
static_assert(kMoneyCave >= sdv::kShellAddr + sdv::kShellSize,
              "money stub must not sit inside the shell body");
static_assert(kMoneyCave + kMoneyStub * 4 <= kMoneyTextEnd,
              "money stub must fit in the executable padding");

// The last amount shown on the money page, kept out here so opening the menu
// again starts from what was set rather than from a hard-coded 60,000.
static u32 gMoneySet = 60000;

u32 movzW0(u32 value) {
    return 0x52800000u | ((value & 0xFFFFu) << 5);
}

u32 movkW0Hi(u32 value) {
    return 0x72A00000u | (((value >> 16) & 0xFFFFu) << 5);
}

u32 branchTo(u32 from, u32 to) {
    return 0x14000000u | (((to - from) >> 2) & 0x03FFFFFFu);
}

bool isBranch(u32 word) {
    return (word & 0xFC000000u) == 0x14000000u;
}

bool setMoney(u32 value) {
    if (!attach()) return false;
    if (value > kMoneyMax) value = kMoneyMax;

    // Two guards before anything is written.  The site must still be the load
    // (or our own branch), and the cave must still be empty padding.  Either
    // check failing means this build's layout is not the one these offsets
    // were taken from, and a write would land in unrelated code.
    u32 site = 0;
    if (!peek(kMoneyInsn, &site, sizeof(site))) {
        setStatus("读取失败");
        return false;
    }
    if (site != kMoneyOrig && !isBranch(site)) {
        setStatus("地址不符 已拒绝");
        logError("money: site holds %08X, expected %08X", (unsigned)site,
                 (unsigned)kMoneyOrig);
        return false;
    }

    u32 cave[kMoneyStub] = { 0, 0, 0, 0 };
    if (!peek(kMoneyCave, cave, sizeof(cave))) {
        setStatus("读取失败");
        return false;
    }
    const bool blank = cave[0] == 0 && cave[1] == 0 && cave[2] == 0 && cave[3] == 0;
    const bool ours  = cave[3] == kMoneyRet && cave[2] == kMoneyPop &&
                       (cave[0] & 0xFFE0001Fu) == 0x52800000u;
    // build 14's stub, which had no epilogue.  Recognising it means a console
    // that ran the crashing build can be upgraded in place; without this the
    // guard would read those three words as a foreign occupant and refuse to
    // write until the game was restarted.
    const bool ours14 = cave[3] == 0 && cave[2] == kMoneyRet &&
                        (cave[0] & 0xFFE0001Fu) == 0x52800000u;
    if (!blank && !ours && !ours14) {
        setStatus("代码洞被占用");
        logError("money: cave holds %08X %08X %08X %08X (refusing)",
                 (unsigned)cave[0], (unsigned)cave[1], (unsigned)cave[2],
                 (unsigned)cave[3]);
        return false;
    }

    // The epilogue word is part of the stub, not an optional extra: without it
    // this returns with sp still 16 bytes low.
    const u32 stub[kMoneyStub] = { movzW0(value), movkW0Hi(value),
                                   kMoneyPop, kMoneyRet };
    if (!poke(kMoneyCave, stub, sizeof(stub))) {
        setStatus("写桩失败");
        return false;
    }
    const u32 br = branchTo((u32)kMoneyInsn, (u32)kMoneyCave);
    if (!poke(kMoneyInsn, &br, sizeof(br))) {
        setStatus("写跳转失败");
        return false;
    }

    logLine("money: %u via cave (site %08X -> %08X, stub %08X %08X %08X %08X)",
            (unsigned)value, (unsigned)kMoneyInsn, (unsigned)br,
            (unsigned)stub[0], (unsigned)stub[1], (unsigned)stub[2],
            (unsigned)stub[3]);
    char msg[48];
    std::snprintf(msg, sizeof(msg), "金钱 %u", (unsigned)value);
    setStatus(msg);
    return true;
}

bool restoreMoney() {
    if (!attach()) return false;

    const u32 insn = kMoneyOrig;
    if (!poke(kMoneyInsn, &insn, sizeof(insn))) {
        setStatus("还原失败");
        return false;
    }
    // The stub is left where it is.  Clearing it would put four zero words into
    // executable memory, and the one thing that must not be there is a landing
    // site -- a core whose instruction cache still holds the old branch, or a
    // thread already inside the stub, would execute 00 00 00 00 and take the
    // game down at the exact moment the user asked for things to be safe.  With
    // the site back to the load nothing can reach it, and setMoney() recognises
    // its own stub when it next writes.
    logLine("money: restored %08X (stub left in place)", (unsigned)kMoneyInsn);
    setStatus("金钱已还原");
    return true;
}

// True when the accessor has been pointed at the stub, so the page can say
// which state it is in instead of guessing.
bool moneyActive() {
    u32 site = 0;
    return peek(kMoneyInsn, &site, sizeof(site)) && isBranch(site);
}


// Date and time.
//
//   Game1.dayOfMonth   module+0x0E27F7A8   (int32, 1..28)
//   Game1.timeOfDay    module+0x0E27F7B0   (int32, HHMM: 600 = 6:00)
//
// These are plain static fields, which is what makes them touchable at all --
// and also what makes them the riskiest thing in the cheat file: writing the
// day does not run the day-boundary logic, so crops do not grow and NPC
// schedules do not advance.  It moves the clock, nothing more.  The page says
// so, and the two writes are separate so a mistaken day can be put back
// without also moving the clock.
//
// The pair above is the current build.  Its update translated Game1's whole
// static block by 0x19238F8: staminaRect, dialogueFont, smallFont, eventUp,
// season and dayOfMonth all move by exactly that, and season stays 0x88 ahead
// of dayOfMonth -- so the block was shifted, not reshuffled, and timeOfDay
// keeps the old +8.  The earlier pair stays as a fallback, because both are
// validated against a plausible day and a plausible clock before either is
// written: if the console is on the older layout, the new pair fails the check
// and the old one succeeds.  Picking the wrong offset therefore refuses to
// write instead of writing a day number over an unrelated field.
struct DateFields {
    u64 day;
    u64 time;
};

constexpr DateFields kDateFields16153 = { 0x0E27F7A8, 0x0E27F7B0 };
constexpr DateFields kDateFieldsOlder = { 0x0C95BEB0, 0x0C95BEB8 };

u32 readField(u64 off) {
    u32 v = 0;
    if (!peek(off, &v, sizeof(v))) return 0;
    return v;
}

bool dayPlausible(u32 v) {
    return v >= 1 && v <= 28;
}

// HHMM, not minutes: 600 is 6:00 and 2600 is 2:00 the next morning.  A value
// whose minute part is 60 or more is not a time this game ever produces, which
// is what makes this a real check rather than a range guess.
bool clockPlausible(u32 v) {
    return v >= 600 && v <= 2600 && (v % 100) < 60;
}

bool dateFieldsUsable(const DateFields& f) {
    return dayPlausible(readField(f.day)) && clockPlausible(readField(f.time));
}

DateFields gDateFields = { 0, 0 };

// Resolved once and remembered.  A failed probe is not cached: the title
// screen has day == 0, and remembering that would lock the page into
// "unrecognised" for the rest of the session.
DateFields dateFields() {
    if (gDateFields.day) return gDateFields;
    if (dateFieldsUsable(kDateFields16153)) {
        gDateFields = kDateFields16153;
        logLine("date fields: current layout (%08llX / %08llX)",
                (unsigned long long)gDateFields.day,
                (unsigned long long)gDateFields.time);
    } else if (dateFieldsUsable(kDateFieldsOlder)) {
        gDateFields = kDateFieldsOlder;
        logLine("date fields: older layout (%08llX / %08llX)",
                (unsigned long long)gDateFields.day,
                (unsigned long long)gDateFields.time);
    }
    return gDateFields;
}

bool writeField(u64 off, u32 value) {
    if (!attach()) return false;
    const u32 before = readField(off);
    if (!poke(off, &value, sizeof(value))) {
        setStatus("写入失败");
        logError("field %08X: write %u failed", (unsigned)off, (unsigned)value);
        return false;
    }
    // Read back.  A write can be accepted by the debugger and still not land
    // -- a read-only page, or a field the game rewrites within the same frame.
    // Silently claiming success is how a wrong offset stays unnoticed.
    const u32 after = readField(off);
    if (after != value) {
        logError("field %08X: wrote %u, read back %u", (unsigned)off,
                 (unsigned)value, (unsigned)after);
        setStatus("写入未生效");
        return false;
    }
    logLine("field %08X: %u -> %u", (unsigned)off, (unsigned)before, (unsigned)value);
    return true;
}

// timeOfDay is an integer in HHMM form in this game (600 = 6:00, 1250 = 12:50),
// so anything of 100 or more cannot be an hour and the value alone decides the
// unit.  The bound is 100 rather than "above 100" because 100 is exactly 1:00 --
// the case a strict comparison would render as "100 点".
bool timeIsMinutes(u32 v) {
    return v >= 100;
}

std::string clockText(u32 v) {
    char buf[16];
    if (v == 0) {
        std::snprintf(buf, sizeof(buf), "--");
    } else if (timeIsMinutes(v)) {
        std::snprintf(buf, sizeof(buf), "%u:%02u", (unsigned)(v / 100), (unsigned)(v % 100));
    } else {
        std::snprintf(buf, sizeof(buf), "%u 点", (unsigned)v);
    }
    return buf;
}

std::string dayText(u32 v) {
    char buf[16];
    if (v == 0) std::snprintf(buf, sizeof(buf), "--");
    else        std::snprintf(buf, sizeof(buf), "%u 日", (unsigned)v);
    return buf;
}

// The clock is edited as two rows rather than one, because one row can only
// step: 30-minute steps reach twelve times a day and no more.  Split into
// hour and minute, every value the game can hold is reachable by pressing in
// one direction, and the minute row never leaves the grid the game uses.
std::string hourText(u32 v) {
    char buf[16];
    if (v == 0) std::snprintf(buf, sizeof(buf), "--");
    else        std::snprintf(buf, sizeof(buf), "%u 点", (unsigned)(v / 100));
    return buf;
}

std::string minuteText(u32 v) {
    char buf[16];
    if (v == 0) std::snprintf(buf, sizeof(buf), "--");
    else        std::snprintf(buf, sizeof(buf), "%02u 分", (unsigned)(v % 100));
    return buf;
}


// Locating the player object without a hard-coded static offset.
//
// The native Switch mod for 1.6.15.3 documents the chain:
//     Farmer + 0x6D8 -> NetStringDictionary owner
//     owner  + 0x48  -> inner Dictionary (count == number of known NPCs)
//
// Those are field offsets, which survive patch releases far better than code
// addresses do.  So instead of looking for Game1.get_player, scan the module's
// writable data for a slot Q such that Q dereferences into that chain.  The
// shape (pointer -> pointer -> object with a small count) is specific enough
// that a false positive is very unlikely.
constexpr u64 kFarmerFriendship = 0x6D8;
constexpr u64 kOwnerDictionary  = 0x48;
constexpr u64 kDictCount        = 0x20;

bool plausiblePointer(u64 v) {
    return v >= 0x10000 && v < 0x0000FFFFFFFFFFFFULL;
}



bool peekAbs(u64 addr, void* out, size_t size);


// This build's Dictionary is split into parallel arrays, not the usual
// (hash,next,key,value) entry struct.  TryGetValue reads:
//   [dict+0x10] buckets : { items +0x10, size +0x20 -> int }
//   [dict+0x18] entries : { items +0x10, size +0x20 -> int }  (8 bytes each)
//   [dict+0x20] keys    : { items +0x10, size +0x20 -> int }  (string* each)
// and the values array follows the same shape.
u64 collItems(u64 coll) { u64 v = 0; peekAbs(coll + 0x10, &v, 8); return v; }
u32 collSize(u64 coll) {
    u64 holder = 0; u32 n = 0;
    if (R_FAILED(dmntchtReadCheatProcessMemory(coll + 0x20, &holder, 8))) return 0;
    if (!plausiblePointer(holder)) return 0;
    if (R_FAILED(dmntchtReadCheatProcessMemory(holder, &n, 4))) return 0;
    return n;
}


// ---------------------------------------------------------------------------
// Friendship editor
//
// Chain (all offsets verified against this build's type metadata):
//   Game1.get_player      -> module+0xC95BB50
//   Farmer.friendshipData -> farmer+0x6D8        (NetStringDictionary)
//   inner Dictionary      -> owner+0x58
//   keys   -> dict+0x20 { items +0x10, size +0x20 -> int* }
//   values -> dict+0x28 { items +0x10 }          (NetRef<Friendship>)
//   Friendship            -> netref+0x68
//   points NetInt         -> friendship+0x10
//   point value           -> netint+0x68
// ---------------------------------------------------------------------------
struct NpcEntry { char name[40]; u64 netint; int points; };
// The dictionary's backing array is sized by growth, not by population: this
// save reports 109 slots for ~34 villagers and the rest are empty.  Iterating
// them is cheap -- an empty slot fails the pointer check on the first read --
// so the only real limit is how many rows the page can hold.
constexpr int kMaxNpcs = 160;
static NpcEntry gNpcs[kMaxNpcs];
static int gNpcCount = 0;
static tsl::elm::ListItem* gNpcRows[kMaxNpcs] = {nullptr};

bool pokeAbs(u64 addr, const void* data, size_t size) {
    return R_SUCCEEDED(dmntchtWriteCheatProcessMemory(addr, data, size));
}

int refreshNpcs() {
    gNpcCount = 0;
    u64 farmer = 0;
    if (!peek(0x0C95BB50ULL, &farmer, 8) || !plausiblePointer(farmer)) return 0;
    u64 owner = 0, dict = 0;
    peekAbs(farmer + 0x6D8, &owner, 8);
    if (!plausiblePointer(owner)) return 0;
    peekAbs(owner + 0x58, &dict, 8);
    if (!plausiblePointer(dict)) return 0;

    u64 keysColl = 0, valsColl = 0;
    peekAbs(dict + 0x20, &keysColl, 8);
    peekAbs(dict + 0x28, &valsColl, 8);
    if (!plausiblePointer(keysColl) || !plausiblePointer(valsColl)) return 0;

    // collSize reads a count through two indirections; if either hop lands on
    // stale memory the value can be absurd, and iterating it would issue
    // billions of IPC reads and wedge the console.  Clamp before looping.
    //
    // The bound used to be 64, which rejected the real value: this dictionary
    // is backed by a grown array, so it reports 109 for a village of ~34, and
    // everything past slot 31 -- Sam, Shane, Vincent, anyone from a mod -- was
    // silently missing from the page.  Empty slots cost one failed read and
    // are skipped by the pointer check below.
    u32 n = collSize(keysColl);
    if (n == 0 || n > 512) {
        logError("npcs: bad size %u, clamping to 32", n);
        n = 32;
    }
    if (n > (u32)kMaxNpcs) n = kMaxNpcs;
    u64 keyItems = collItems(keysColl), valItems = collItems(valsColl);
    if (!plausiblePointer(keyItems) || !plausiblePointer(valItems)) {
        logError("npcs: items bad %llX %llX", (unsigned long long)keyItems,
                 (unsigned long long)valItems);
        return 0;
    }
    logLine("npcs: size=%u keys=%llX vals=%llX", n, (unsigned long long)keyItems,
            (unsigned long long)valItems);

    for (u32 i = 0; i < n && gNpcCount < kMaxNpcs; ++i) {
        u64 key = 0, netref = 0, friendship = 0, netint = 0;
        peekAbs(keyItems + i * 8, &key, 8);
        peekAbs(valItems + i * 8, &netref, 8);
        if (!plausiblePointer(key) || !plausiblePointer(netref)) continue;
        peekAbs(netref + 0x68, &friendship, 8);
        if (!plausiblePointer(friendship)) continue;
        peekAbs(friendship + 0x10, &netint, 8);
        if (!plausiblePointer(netint)) continue;

        int len = 0;
        if (R_FAILED(dmntchtReadCheatProcessMemory(key + 0x10, &len, 4)) || len <= 0 || len >= 40) continue;
        u16 ch[40] = {0};
        if (R_FAILED(dmntchtReadCheatProcessMemory(key + 0x14, ch, len * 2))) continue;

        NpcEntry& e = gNpcs[gNpcCount];
        for (int k = 0; k < len; ++k) e.name[k] = (ch[k] < 128) ? (char)ch[k] : '?';
        e.name[len] = 0;
        e.netint = netint;
        e.points = -1;
        peekAbs(netint + 0x68, &e.points, 4);
        logLine("  npc[%d] '%s' netint=%llX pts=%d", gNpcCount, e.name,
                (unsigned long long)netint, e.points);
        ++gNpcCount;
    }
    return gNpcCount;
}

// NetInt keeps value / previousValue / targetValue side by side; writing all
// three keeps the netcode layer from restoring the old number on the next tick.
// Never write blind: read the current value first and only proceed when it
// looks like a real friendship score.  A stale pointer would otherwise send
// 2500 into arbitrary game memory, which is exactly how the process died.
bool setNpcPoints(int idx, int value) {
    if (idx < 0 || idx >= gNpcCount) return false;
    const u64 netint = gNpcs[idx].netint;
    int current = -1;
    if (R_FAILED(dmntchtReadCheatProcessMemory(netint + 0x68, &current, 4))) return false;
    if (current < 0 || current > 3000) {
        logError("setNpc: refusing, current=%d netint=%llX", current,
                 (unsigned long long)netint);
        return false;
    }
    pokeAbs(netint + 0x68, &value, 4);
    pokeAbs(netint + 0x6C, &value, 4);
    pokeAbs(netint + 0x70, &value, 4);
    gNpcs[idx].points = value;
    logLine("setNpc: %s %d -> %d", gNpcs[idx].name, current, value);
    return true;
}

