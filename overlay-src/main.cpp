// Diagnostics go to a file, not to the screen.  A status line is about forty
// characters wide, which is not enough to tell apart "attach failed" from
// "attach succeeded but the handle is stale" - and that difference is the
// whole question right now.  The log is plain text on the SD card and can be
// read from a PC without asking anyone to transcribe numbers.
bool gFsMounted = false;

// Error lines are prefixed with "!! " so the rotation step can keep them while
// dropping the routine ones.  Losing the one line that explained a failure is
// worse than keeping a file that slowly grows.
void logWrite(const char* prefix, const char* fmt, va_list ap) {
    if (!gFsMounted) {
        fsdevMountSdmc();
        gFsMounted = true;
    }

    {
        FILE* probe = std::fopen("sdmc:/sdv_log.txt", "r");
        if (probe) {
            std::fseek(probe, 0, SEEK_END);
            const long size = std::ftell(probe);
            std::fclose(probe);
            if (size > 64 * 1024) {
                // Keep every error line, drop the rest.
                static char keep[16 * 1024];
                size_t kept = 0;
                FILE* in = std::fopen("sdmc:/sdv_log.txt", "r");
                if (in) {
                    char line[256];
                    while (std::fgets(line, sizeof(line), in)) {
                        if (line[0] == '!' && line[1] == '!') {
                            const size_t n = std::strlen(line);
                            if (kept + n + 1 < sizeof(keep)) {
                                std::memcpy(keep + kept, line, n);
                                kept += n;
                            }
                        }
                    }
                    std::fclose(in);
                }
                FILE* out = std::fopen("sdmc:/sdv_log.txt", "w");
                if (out) {
                    if (kept) std::fwrite(keep, 1, kept, out);
                    std::fclose(out);
                }
            }
        }
    }

    FILE* f = std::fopen("sdmc:/sdv_log.txt", "a");
    if (!f) return;
    std::fputs(prefix, f);
    std::vfprintf(f, fmt, ap);
    std::fputc('\n', f);
    std::fclose(f);
}

void logError(const char* fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    logWrite("!! ", fmt, ap);
    va_end(ap);
}

void logLine(const char* fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    logWrite("", fmt, ap);
    va_end(ap);
}

