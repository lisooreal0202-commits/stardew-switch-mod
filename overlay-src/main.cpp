// --- persisted settings ---------------------------------------------------
//
// A Tesla overlay is a fresh process every time the menu opens, so every global
// starts over: quantity back to 10, quality back to normal, query back to empty.
// On hardware that showed up as "set 999, reopen the menu, it is 10 again" and
// as retyping the same keyword five times in one sitting (sdv_log: six separate
// `inset kept` lines, six `view=keypad q=""` right behind them).
//
// The search page deliberately has no amount or quality control of its own: two
// 90 px track bars would eat 250 of the 522 px content box and leave two result
// rows on screen.  Persisting the setting is what makes "set it once" enough,
// and the L/R shortcut on the result page covers changing it without leaving.
constexpr const char* kCfgPath = "sdmc:/sdv_items.cfg";

void ensureFs() {
    if (!gFsMounted) {
        fsdevMountSdmc();
        gFsMounted = true;
    }
}

void saveConfig() {
    ensureFs();
    FILE* f = std::fopen(kCfgPath, "w");
    if (!f) return;
    std::fprintf(f, "amount=%u\nquality=%u\nquery=%s\none_hit=%d\nauto_water=%d\nall_recipes=%d\nall_collections=%d\n"
                    "speed=%d\nauto_fish=%d\nstamina=%d\ngather=%d\ngather_lock=%d\nwater_can=%d\nmoney=%u\n",
                 (unsigned)gAmount, (unsigned)gQuality, gQuery,
                 (int)gCfg.oneHitKill, (int)gCfg.autoWater, (int)gCfg.allRecipes,
                 (int)gCfg.allCollections,
                 gCfg.speed, (int)gCfg.autoFish, (int)gCfg.stamina,
                 gCfg.gather, (int)gCfg.gatherLock, (int)gCfg.waterCan,
                 (unsigned)gCfg.money);
    std::fclose(f);
}

void loadConfig() {
    ensureFs();
    FILE* f = std::fopen(kCfgPath, "r");
    if (!f) return;

    char line[128];
    while (std::fgets(line, sizeof(line), f)) {
        line[std::strcspn(line, "\r\n")] = '\0';

        if (std::strncmp(line, "amount=", 7) == 0) {
            const int want = std::atoi(line + 7);
            // Only accept a value that is actually on the ladder, otherwise the
            // bars would come up with no step selected.
            for (int i = 0; i < kAmountStepCount; ++i)
                if (kAmountSteps[i] == want) gAmount = kAmountSteps[i];
        } else if (std::strncmp(line, "quality=", 8) == 0) {
            const int want = std::atoi(line + 8);
            for (int i = 0; i < kQualityStepCount; ++i)
                if (kQualitySteps[i] == want) gQuality = kQualitySteps[i];
        } else if (std::strncmp(line, "one_hit=", 8) == 0) {
            gCfg.oneHitKill = std::atoi(line + 8) != 0;
        } else if (std::strncmp(line, "auto_water=", 11) == 0) {
            gCfg.autoWater = std::atoi(line + 11) != 0;
        } else if (std::strncmp(line, "all_recipes=", 12) == 0) {
            gCfg.allRecipes = std::atoi(line + 12) != 0;
        } else if (std::strncmp(line, "all_collections=", 16) == 0) {
            gCfg.allCollections = std::atoi(line + 16) != 0;
        } else if (std::strncmp(line, "speed=", 6) == 0) {
            const int want = std::atoi(line + 6);
            if (want >= 0 && want < kSpeedCount) gCfg.speed = want;
        } else if (std::strncmp(line, "auto_fish=", 10) == 0) {
            gCfg.autoFish = std::atoi(line + 10) != 0;
        } else if (std::strncmp(line, "stamina=", 8) == 0) {
            gCfg.stamina = std::atoi(line + 8) != 0;
        } else if (std::strncmp(line, "gather=", 7) == 0) {
            const int want = std::atoi(line + 7);
            if (want >= 0 && want < kGatherCount) gCfg.gather = want;
        } else if (std::strncmp(line, "gather_lock=", 12) == 0) {
            gCfg.gatherLock = std::atoi(line + 12) != 0;
        } else if (std::strncmp(line, "water_can=", 10) == 0) {
            gCfg.waterCan = std::atoi(line + 10) != 0;
        } else if (std::strncmp(line, "money=", 6) == 0) {
            const long want = std::strtol(line + 6, nullptr, 10);
            gCfg.money = (want > 0 && want <= (long)kMoneyMax) ? (unsigned)want : 0;
            // The page remembers the last amount separately from whether it is
            // on, so turning it off does not throw the number away.
            if (gCfg.money) gMoneySet = gCfg.money;
        } else if (std::strncmp(line, "query=", 6) == 0) {
            std::strncpy(gQuery, line + 6, kQueryMax);
            gQuery[kQueryMax] = '\0';
            gQueryDirty = true;
        }
    }
    std::fclose(f);
}

// L/R on the result page.  Step one notch and store it, so the choice survives
// the next launch even if the menu is closed immediately afterwards.
void cycleAmount(int dir) {
    int i = amountIndex() + dir;
    if (i < 0) i = kAmountStepCount - 1;
    if (i >= kAmountStepCount) i = 0;
    gAmount = kAmountSteps[i];
    saveConfig();
}

void cycleQuality(int dir) {
    int i = qualityIndex() + dir;
    if (i < 0) i = kQualityStepCount - 1;
    if (i >= kQualityStepCount) i = 0;
    gQuality = kQualitySteps[i];
    saveConfig();
}

// L / R / Y.  One implementation for both pages: the two used to be separate
// ideas (track bars here, shortcut keys there) and that is exactly the kind of
// duplication that ends up out of sync.  Returns true when something changed, so
// the caller knows to repaint its status line.
bool handleSettingKeys(u64 keysDown) {
    bool changed = false;
    if (keysDown & HidNpadButton_L) { cycleAmount(-1); changed = true; }
    if (keysDown & HidNpadButton_R) { cycleAmount(1);  changed = true; }
    if (keysDown & HidNpadButton_Y) { cycleQuality(1); changed = true; }
    if (changed) logLine("settings %s", settingsText().c_str());
    return changed;
}

// tsl::gfx::Renderer::a() applies the overlay's global fade to a colour; the
// upstream name is a single letter, which is not worth copying everywhere.
inline tsl::Color fade(const tsl::Color& c) {
    return tsl::gfx::Renderer::a(c);
}

bool queryMatches(int idx, const char* q) {
    if (!q[0]) return false;

    // A leading digit means "find by number": the id is compared as text, so
    // "13" lists the 13x range and "130" is exactly 130.
    if (q[0] >= '0' && q[0] <= '9') {
        const char* id = sdv::kItems[idx].id;
        while (*id && (*id < '0' || *id > '9')) ++id;   // skip "(O)" / "(F)"
        for (int i = 0; q[i]; ++i) {
            if (id[i] == '\0' || id[i] != q[i]) return false;
        }
        return id[0] != '\0';
    }

    return std::strstr(sdv::kSearchKeys[idx], q) != nullptr;
}

int searchCount(const char* q) {
    int n = 0;
    for (int i = 0; i < sdv::kItemCount; ++i)
        if (queryMatches(i, q)) ++n;
    return n;
}

// Recompute lazily: draw() runs every frame, but the query only changes when a
// key is pressed.
void refreshQueryHits() {
    if (!gQueryDirty) return;
    gQueryDirty = false;
    gQueryHits  = gQuery[0] ? searchCount(gQuery) : 0;
}

void queryAppend(char c) {
    const size_t n = std::strlen(gQuery);
    if (n + 1 >= kQueryMax) return;
    // Fold to lower case here, once, rather than case-folding 683 keys per
    // keystroke.  Digits pass through untouched.
    if (c >= 'A' && c <= 'Z') c = static_cast<char>(c - 'A' + 'a');
    gQuery[n]     = c;
    gQuery[n + 1] = '\0';
    gQueryDirty   = true;
    saveConfig();      // the query outlives this process too; see kCfgPath
}

void queryBackspace() {
    const size_t n = std::strlen(gQuery);
    if (n) gQuery[n - 1] = '\0';
    gQueryDirty = true;
    saveConfig();
}

void queryClear() {
    gQuery[0]   = '\0';
    gQueryDirty = true;
    saveConfig();
}

