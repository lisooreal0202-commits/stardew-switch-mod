std::string moneyText(u32 v) {
    char raw[16];
    std::snprintf(raw, sizeof(raw), "%u", (unsigned)v);
    std::string s(raw), out;
    int c = 0;
    for (int i = (int)s.size() - 1; i >= 0; --i) {
        out.insert(out.begin(), s[(size_t)i]);
        if (++c % 3 == 0 && i > 0) out.insert(out.begin(), ',');
    }
    return out + " g";
}

// One press has to be able to reach the ceiling without two hundred presses,
// and has to be able to land on 12,340 without only ever hitting round
// numbers.  The step follows the magnitude for exactly that reason -- the top
// bands are what make 999,999,999 reachable at all.
u32 moneyStep(u32 v) {
    if (v < 10000)      return 1000;
    if (v < 100000)     return 10000;
    if (v < 1000000)    return 100000;
    if (v < 10000000)   return 1000000;
    if (v < 100000000)  return 10000000;
    return 100000000;
}

