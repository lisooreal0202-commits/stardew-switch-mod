// Do the switches on screen match what is actually patched in memory?
//
// The switches are persisted to a file; the patches live in the running process.
// A kill between the poke and the save, an older .ovl that patched something
// this build's config does not mention, or a game still running from a session
// where a switch was flipped all leave the two out of step -- and the menu then
// shows "已关" over a patch that is on.  Not fatal (the next toggle fixes it),
// but it makes every report about a switch suspect, so the log states it
// outright instead of leaving it to be inferred from numbers pages apart.
// 1 when every word in the group carries the patch, 0 when every word is still
// pristine, -1 when it is neither -- a half-applied group is the state that
// breaks the feature while the switch claims to be on, so it is reported as
// loudly as a disagreement.
int groupState(const WordPatch* sites, int n) {
    int on = 0, off = 0;
    for (int i = 0; i < n; ++i) {
        u32 cur = 0;
        if (!peek(sites[i].off, &cur, sizeof(cur))) return -1;
        if      (cur == sites[i].patched) ++on;
        else if (cur == sites[i].orig)    ++off;
        else                              return -1;
    }
    if (on == n)  return 1;
    if (off == n) return 0;
    return -1;
}

void checkToggleConsistency() {
    u32 wDmgMax = 0, wDmgMin = 0, wWater = 0, wRecipe = 0, wColl = 0;
    peek(kDmgMaxOff, &wDmgMax, sizeof(wDmgMax));
    peek(kDmgMinOff, &wDmgMin, sizeof(wDmgMin));
    peek(kWaterOff, &wWater, sizeof(wWater));
    peek(kRecipeGateOff, &wRecipe, sizeof(wRecipe));
    peek(kCollectSites[0].off, &wColl, sizeof(wColl));

    // The one-hitter writes two words.  If only one landed, the range the game
    // uses is unchanged and the switch is lit while doing nothing.
    if ((wDmgMax == kDmgMaxHit) != (wDmgMin == kDmgMinHit))
        logError("toggles: one-hit half applied (max=%08X min=%08X)",
                 (unsigned)wDmgMax, (unsigned)wDmgMin);

    const bool dmgOn    = wDmgMax == kDmgMaxHit;
    const bool waterOn  = wWater  == kWaterOn;
    const bool recipeOn = wRecipe == kRecipeGateNop;
    const bool collOn   = wColl   == kCollectTrue;

    // The six group patches, the two index patches and the money cave were all
    // added after this check was written, and for two builds the log announced
    // "memory and config agree" having compared four switches out of eleven.
    // A report covering a third of the switches is worse than none: it is the
    // line people quote back when something is clearly wrong.
    const int fishS = groupState(kFishSites, kFishCount);
    const int stamS = groupState(kStaminaSites, kStaminaCount);
    const int lockS = groupState(kLockSites, 1);
    const int canS  = groupState(kCanSites, 1);

    u32 wLo = 0, wHi = 0, wGather = 0;
    peek(kWalkLoOff, &wLo, sizeof(wLo));
    peek(kWalkHiOff, &wHi, sizeof(wHi));
    peek(kGatherOff, &wGather, sizeof(wGather));
    int speedIdx = -1, gatherIdx = -1;
    for (int i = 0; i < kSpeedCount; ++i)
        if (wLo == kSpeedLevels[i].lo && wHi == kSpeedLevels[i].hi) {
            speedIdx = i;
            break;
        }
    for (int i = 0; i < kGatherCount; ++i)
        if (wGather == kGatherWords[i]) {
            gatherIdx = i;
            break;
        }

    const bool moneyOn = moneyActive();

    const bool bad =
        dmgOn    != gCfg.oneHitKill      ||
        waterOn  != gCfg.autoWater       ||
        recipeOn != gCfg.allRecipes      ||
        collOn   != gCfg.allCollections  ||
        stamS    != (gCfg.stamina    ? 1 : 0) ||
        lockS    != (gCfg.gatherLock ? 1 : 0) ||
        canS     != (gCfg.waterCan   ? 1 : 0) ||
        gatherIdx != gCfg.gather              ||
        moneyOn  != (gCfg.money != 0);

    if (bad) {
        logError("toggles: memory/config disagree"
                 " dmg=%d/%d water=%d/%d recipe=%d/%d coll=%d/%d"
                 " spd=%d/%d fish=%d/%d stam=%d/%d gath=%d/%d"
                 " lock=%d/%d can=%d/%d money=%d/%d",
                 (int)dmgOn, (int)gCfg.oneHitKill, (int)waterOn, (int)gCfg.autoWater,
                 (int)recipeOn, (int)gCfg.allRecipes,
                 (int)collOn, (int)gCfg.allCollections,
                 speedIdx, gCfg.speed, fishS, (int)gCfg.autoFish,
                 stamS, (int)gCfg.stamina, gatherIdx, gCfg.gather,
                 lockS, (int)gCfg.gatherLock, canS, (int)gCfg.waterCan,
                 (int)moneyOn, (int)(gCfg.money != 0));
        return;
    }
    logLine("toggles: memory and config agree (all 11 switches)");
}

bool attach() {
    if (gOpen) return true;

    // A successful open does not mean the handle can WRITE.  dmntcht has handed
    // back handles that read fine and reject every write with 0xD401 -- that is
    // exactly "shell body write failed rc=0000D401", six times in a row.  Probe
    // with a no-op write (put the current word back where it already is) and
    // reopen when it fails, instead of leaving a dead handle latched in gOpen.
    for (int attempt = 0; attempt < 4; ++attempt) {
        if (!attachOnce()) return false;

        u32 probe = 0;
        if (peek(kScratch, &probe, sizeof(probe)) && poke(kScratch, &probe, sizeof(probe)))
            return true;

        logError("  handle opened but is not writable, reopening (%d/4)", attempt + 1);
        detach();
        svcSleepThread(120'000'000ULL);
    }

    setStatus("句柄不可用");
    return false;
}

static bool attachOnce() {

    // sm has to be up before dmntchtInitialize can look the service up, and
    // libtesla does not guarantee it is.  Without this the very first call
    // always failed, the probe below happened to initialise sm as a side
    // effect, and the second click worked - which is exactly the "press it
    // twice" behaviour this replaces.
    smInitialize();

    Result rc = dmntchtInitialize();
    if (R_FAILED(rc)) {
        std::snprintf(gStatus, sizeof(gStatus), "dmnt:cht 失败 %08X", (unsigned)rc);
        logError("dmntchtInitialize failed rc=%08X", (unsigned)rc);
        return false;
    }

    // Attaching is the whole ballgame, and its result was never checked
    // before.  Close first so a stale half-open state cannot mask a failure.
    dmntchtForceCloseCheatProcess();
    Result rOpen = dmntchtForceOpenCheatProcess();

    bool has = false;
    Result rHas = dmntchtHasCheatProcess(&has);
    if (R_FAILED(rOpen) || R_FAILED(rHas) || !has) {
        std::snprintf(gStatus, sizeof(gStatus), "挂载失败 开%08X 查%08X 有%d",
                      (unsigned)rOpen, (unsigned)rHas, has ? 1 : 0);
        dmntchtExit();
        return false;
    }

    DmntCheatProcessMetadata meta{};
    Result rMeta = dmntchtGetCheatProcessMetadata(&meta);
    if (R_FAILED(rMeta)) {
        std::snprintf(gStatus, sizeof(gStatus), "元数据失败 %08X", (unsigned)rMeta);
        dmntchtExit();
        return false;
    }
    if (meta.title_id != kTitleId) {
        setStatus("当前不是星露谷");
        dmntchtExit();
        return false;
    }

    // The offsets baked into the shell belong to one build of the game.  A
    // different build means different function addresses, and writing there
    // corrupts the game instead of failing - so refuse before touching
    // anything.  The expected id is the same string the cheat file was named
    // after, which is how it was verified in the first place.
    static constexpr u8 kBuildId[8] = { 0xE7, 0xF8, 0x45, 0x09,
                                        0x3E, 0x8C, 0xBC, 0x68 };
    if (std::memcmp(meta.main_nso_build_id, kBuildId, sizeof(kBuildId)) != 0) {
        setStatus("版本不匹配");
        logError("build id mismatch: %02X%02X%02X%02X%02X%02X%02X%02X",
                 meta.main_nso_build_id[0], meta.main_nso_build_id[1],
                 meta.main_nso_build_id[2], meta.main_nso_build_id[3],
                 meta.main_nso_build_id[4], meta.main_nso_build_id[5],
                 meta.main_nso_build_id[6], meta.main_nso_build_id[7]);
        dmntchtExit();
        return false;
    }

    // The base of the main NSO is the one number everything else depends on.
    // Our offline addresses assume it is 0; if it is not, every write lands in
    // the wrong place and the first one takes the game down.
    // Print the id that just passed the check: the failure path logs a mismatch,
    // so a report with no id in it is indistinguishable from one where the
    // check never ran at all.
    logLine("    build id %02X%02X%02X%02X%02X%02X%02X%02X (matches)",
            meta.main_nso_build_id[0], meta.main_nso_build_id[1],
            meta.main_nso_build_id[2], meta.main_nso_build_id[3],
            meta.main_nso_build_id[4], meta.main_nso_build_id[5],
            meta.main_nso_build_id[6], meta.main_nso_build_id[7]);
    logLine("--- attach ok: pid=%llu title=%016llX base=%llX size=%llX",
            (unsigned long long)meta.process_id,
            (unsigned long long)meta.title_id,
            (unsigned long long)meta.main_nso_extents.base,
            (unsigned long long)meta.main_nso_extents.size);
    logLine("    open=%08X has=%08X", (unsigned)rOpen, (unsigned)rHas);

    gNsoBase = meta.main_nso_extents.base;
    gNsoSize = meta.main_nso_extents.size;
    gPid     = meta.process_id;
    gOpen = true;

    // The four instructions this build patches, as they stand right now.
    // Reading them costs one syscall each and answers both questions that come
    // with every report: is this the game build the offsets belong to, and has
    // the patch already been applied?  The values are the pristine words except
    // where a toggle is on -- hook=15A1AECD and recipe=D503201F mean patched.
    {
        u32 wHook = 0, wRecipe = 0, wDmg = 0, wDmgMin = 0, wColl = 0, wWater = 0;
        peek(sdv::kHookAddr, &wHook, sizeof(wHook));
        peek(kRecipeGateOff, &wRecipe, sizeof(wRecipe));
        peek(kDmgMaxOff, &wDmg, sizeof(wDmg));
        peek(kDmgMinOff, &wDmgMin, sizeof(wDmgMin));
        peek(kCollectSites[0].off, &wColl, sizeof(wColl));
        peek(kWaterOff, &wWater, sizeof(wWater));
        logLine("    patch sites: hook=%08X recipe=%08X dmg=%08X/%08X coll=%08X water=%08X",
                (unsigned)wHook, (unsigned)wRecipe, (unsigned)wDmg,
                (unsigned)wDmgMin, (unsigned)wColl, (unsigned)wWater);
        logLine("      pristine 910023E0 / 3607FE80 / 2A0403F6+2A0303F5 / %08X / 2A1F03E1",
                (unsigned)kCollectSites[0].orig);
        // The absolute address, not just the word.  Two reports showed the
        // damage site already patched in a process that had just started -- a
        // fresh pid and a fresh base -- which is only possible if the write is
        // landing somewhere that outlives the process.  The address decides
        // that: same address across two pids means it is not the game's text.
        logLine("      dmg site at %016llX (base %016llX + %08X)",
                (unsigned long long)(gNsoBase + kDmgMaxOff),
                (unsigned long long)gNsoBase, (unsigned)kDmgMaxOff);
    }

    // The subtitle is one right-aligned line; "基址4711006000 大小E629000" is
    // wide enough to run into the title.  The numbers are in the attach line
    // above, so the subtitle only has to say that it worked.
    setStatus("已连接");
    return true;
}

void detach() {
    if (!gOpen) return;
    dmntchtExit();
    gOpen = false;
}

// All offline addresses are offsets from the module base.  On hardware that
// base is ASLR'd (measured 0x21ED006000 and 0x2A19806000 on consecutive
// launches), so folding it in here is the only place it has to be right.
bool poke(u64 off, const void* data, size_t size) {
    return R_SUCCEEDED(dmntchtWriteCheatProcessMemory(gNsoBase + off, data, size));
}

// ---------------------------------------------------------------- subsdk8 ---
//
// Communication test only: publish a request into the mod's own slot and let
// the mod read it.  Nothing here touches timeOfDay, the clock or the date.
//
// The slot's address was taken from the built module:
//   aarch64-none-elf-nm -S sdv_native.elf | grep g_timeRequest
//   000000000003d310 0000000000000008 d g_timeRequest
// The three NSO segments match the ELF program headers one for one, so the
// runtime address is module base + 0x3D310.  Re-export if the mod is rebuilt.

constexpr u64 kSubsdkTimeReqOff = 0x3D310ULL;
// First eight bytes of the mod's text: the branch over the NX header, then
// __nx_mod0's offset (0x36BA0) and __nx_modver's (0x36BBC).  Both offsets move
// whenever the module's text changes size, so this has to be re-read from the
// ELF for every build -- it read 0x38C50 in the previous one, which made the
// scan fail with "找不到 subsdk8" instead of finding the wrong module.
//   xxd -l 16 sdv_native.elf at the first LOAD's file offset
constexpr u8  kSubsdkSig[8] = {0x08, 0x00, 0x00, 0x14, 0xA0, 0x6B, 0x03, 0x00};

u64  gSubsdkBase = 0;
char gTimeReqStatus[64] = "未测试";

// Scans the mappings for an executable region whose first bytes match the
// mod's text.  No module list is available through this dmnt struct, so the
// signature is what identifies the module.
u64 findSubsdkBase() {
    if (gSubsdkBase) return gSubsdkBase;
    u64 total = 0;
    if (R_FAILED(dmntchtGetCheatProcessMappingCount(&total))) return 0;
    MemoryInfo chunk[32];
    u64 off = 0;
    while (off < total) {
        u64 got = 0;
        if (R_FAILED(dmntchtGetCheatProcessMappings(chunk, 32, off, &got)) || !got)
            break;
        for (u64 i = 0; i < got; i++) {
            const MemoryInfo& m = chunk[i];
            if (!(m.perm & Perm_X)) continue;
            u8 head[8];
            if (R_FAILED(dmntchtReadCheatProcessMemory(m.addr, head, sizeof(head))))
                continue;
            bool same = true;
            for (int k = 0; k < 8; k++)
                if (head[k] != kSubsdkSig[k]) { same = false; break; }
            if (same) { gSubsdkBase = m.addr; return gSubsdkBase; }
        }
        off += got;
    }
    return 0;
}

// Odd/even seqlock: odd seq means "being written", even means "published".
bool submitTimeRequest(int hhmm) {
    const u64 base = findSubsdkBase();
    if (!base) { std::snprintf(gTimeReqStatus, sizeof(gTimeReqStatus), "找不到 subsdk8"); return false; }

    const u64 addr = base + kSubsdkTimeReqOff;
    u32 seq = 0;
    if (R_FAILED(dmntchtReadCheatProcessMemory(addr, &seq, sizeof(seq)))) {
        std::snprintf(gTimeReqStatus, sizeof(gTimeReqStatus), "读 seq 失败");
        return false;
    }
    const u32 even = (seq + 2u) & ~1u;
    const u32 odd  = even - 1u;
    const s32 tgt  = hhmm;

    if (!pokeAbs(addr, &odd, 4)) {
        std::snprintf(gTimeReqStatus, sizeof(gTimeReqStatus), "写 seq(奇) 失败");
        return false;
    }
    if (!pokeAbs(addr + 4, &tgt, 4)) {
        std::snprintf(gTimeReqStatus, sizeof(gTimeReqStatus), "写 target 失败");
        return false;
    }
    if (!pokeAbs(addr, &even, 4)) {
        std::snprintf(gTimeReqStatus, sizeof(gTimeReqStatus), "写 seq(偶) 失败");
        return false;
    }
    std::snprintf(gTimeReqStatus, sizeof(gTimeReqStatus),
                  "已提交 %d seq %u->%u", hhmm, seq, even);
    return true;
}

// peek() adds the module base; a MonoString object lives on the managed heap at
// an absolute address, so it needs the raw form.
bool peekAbs(u64 addr, void* out, size_t size) {
    return R_SUCCEEDED(dmntchtReadCheatProcessMemory(addr, out, size));
}

bool peek(u64 off, void* out, size_t size) {
    return R_SUCCEEDED(dmntchtReadCheatProcessMemory(gNsoBase + off, out, size));
}

// Write the hook instruction and the shell body.  The hook is a single branch
// word that the shell's own generator already computed; the body is the same
// kShellSize bytes the IPS would have carried (736 in this build -- the money
// stub lives past the end of it, not inside).
bool installShell() {
    if (!attach()) return false;

    // Two writes, two different questions.  The scratch window is ordinary
    // .bss data; the hook sits in .text, which the loader maps read-execute.
    // If data writes succeed and the hook does not, the debug handle is
    // read-only and no amount of retrying will help.
    // Read first.  A successful read next to a failed write means the handle is
    // read-only; a failed read means we are not attached to the memory we think
    // we are, whatever dmntchtHasCheatProcess said.  The third value is the
    // live word at the hook, which should be the original add x0, sp, #8 -
    // proof that the address space we are poking is the one we mapped offline.
    u32 zero = 0;
    Result rData = poke(kScratch, &zero, sizeof(zero)) ? 0 : 0xD401;

    // Body first, hook second.  The other order leaves a window where the game
    // takes the branch into memory that has not been written yet, and that is
    // exactly what started happening once the install ran back-to-back with the
    // first item instead of a menu click apart.
    Result rBody = poke(sdv::kShellAddr, sdv::kShell,
                        sdv::kShellSize) ? 0 : 0xD401;
    if (R_FAILED(rBody)) {
        std::snprintf(gStatus, sizeof(gStatus), "写壳子失败 %08X", (unsigned)rBody);
        logError("shell body write failed rc=%08X", (unsigned)rBody);
        detach();     // do not keep using a read-only handle on the next press
        return false;
    }

    Result rHook = poke(sdv::kHookAddr, &sdv::kHookWord,
                        sizeof(sdv::kHookWord)) ? 0 : 0xD401;
    if (R_FAILED(rHook) || R_FAILED(rData))
        logError("write scratch rc=%08X  hook rc=%08X (addr %08X)",
                 (unsigned)rData, (unsigned)rHook, (unsigned)sdv::kHookAddr);
    else
        logLine("body+hook written, rc=%08X (addr %08X)",
                (unsigned)rHook, (unsigned)sdv::kHookAddr);
    if (R_FAILED(rHook)) {
        std::snprintf(gStatus, sizeof(gStatus), "写跳转失败 %08X", (unsigned)rHook);
        detach();
        return false;
    }
    setStatus("补丁已装");
    return true;
}

// Make sure the hook is in place before using it.  The shell lives in the
// game's own memory, which is fresh on every launch, so this has to be checked
// each time - but it only writes when the hook is actually missing, and it
// means the user never has to press an install button.
bool ensureShell() {
    if (!attach()) return false;

    // The hook word is just `b <cave>` -- it depends on the distance and nothing
    // else, so every build since v15 produces the *same* word.  The prologue is
    // shared too (they all open with the same stp chain), so neither is a
    // fingerprint.  Compare the entire body: 700-odd bytes per give is free
    // next to getting this wrong, which leaves an old shell running silently.
    u32 live = 0;
    const bool hooked = peek(sdv::kHookAddr, &live, sizeof(live)) && live == sdv::kHookWord;

    bool current = false;
    if (hooked) {
        static u8 body[sizeof(sdv::kShell)];
        current = peek(sdv::kShellAddr, body, sizeof(body)) &&
                  std::memcmp(body, sdv::kShell, sizeof(body)) == 0;
    }
    if (current) return true;

    logLine("shell %s (hook=%08X body0=%08X want0=%08X), installing",
            hooked ? "is a different build" : "missing", (unsigned)live,
            (unsigned)(hooked ? 0 : 0), (unsigned)sdv::kShell[0]);
    return installShell();
}

// Post one item to the command block and wait for the shell to consume it.
//
// The latch has to be cleared first: the shell refuses to run while
// scratch[0] is non-zero, and it sets that byte itself on success.  Writing
// the state last means the shell can never see a half-built command.
// Milliseconds since boot.  Used to time-stamp a give and to tell "the user
// tapped twice" apart from "one tap fired twice" -- the log had neither, so a
// run of three identical give lines was unreadable.
u64 nowMs() {
    return svcGetSystemTick() / 19200ULL;   // 19.2 MHz -> ms
}

// What the shell actually built, straight from scratch: length and the first
// four UTF-16 units.  "Gave the wrong item" is otherwise indistinguishable from
// "gave the right one and looked at it wrong".
void logBuiltString(const char* id) {
    u32 slen = 0;
    u64 chars = 0;
    peek(kScratch + 0x20, &slen, sizeof(slen));
    peek(kScratch + 0x28, &chars, sizeof(chars));
    logLine("  built len=%u chars=%016llX (want %s)", (unsigned)slen,
            (unsigned long long)chars, id);
}

bool giveItem(const char* id, const char* name, u8 cat) {
    // One tap, one item.  libtesla delivers a touch release through ListItem's
    // onTouch *and* through the click path, and a 120 ms window is below any
    // human double tap, so an intentional repeat is never swallowed while a
    // double fire is.  Anything the guard eats is logged, so it stays visible.
    // Keyed on (category, id), not id alone: weapon 14 and object 14 are
    // different items, and ids now restart in every registry.
    static u64  lastMs = 0;
    static char lastId[32] = "";
    static u8   lastCat = 0xFF;
    const u64 now = nowMs();
    if (cat == lastCat && std::strcmp(id, lastId) == 0 && now - lastMs < 120) {
        logLine("  duplicate give ignored (cat=%u id=%s, %llu ms after the previous one)",
                (unsigned)cat, id, (unsigned long long)(now - lastMs));
        return true;
    }
    lastMs = now;
    std::strncpy(lastId, id, sizeof(lastId) - 1);
    lastId[sizeof(lastId) - 1] = '\0';
    lastCat = cat;

    if (!ensureShell()) return false;

    // What the quantity setting means depends on the registry:
    //   objects (0-9)   a stack size, and quality applies
    //   everything else one item, always
    //
    // Furniture and shirts used to be passed the quantity, capped at ten, on
    // the theory that wanting several chairs is reasonable.  In practice the
    // bag only ever received one while the menu claimed ten - the game treats
    // these as individual entries.  Passing a number the game ignores made the
    // menu lie, so the number is gone and the page says "只加 1 个" instead.
    const bool      isObject = cat < 10;
    u32             amount   = 1;
    u32             quality  = 0;
    if (isObject) {
        amount  = gAmount;
        quality = gQuality;
    }

    // Record the item before anything is written.  When a particular id takes
    // the game down this line is the only way to know which one it was - the
    // previous freeze left the log ending at the install, with no clue.
    logLine("give %s (%s) amount=%u q=%u t=%llums", id, name,
            (unsigned)amount, (unsigned)quality, (unsigned long long)now);

    u32 magic = kBridgeMagic;
    if (!poke(kBridge, &magic, sizeof(magic))) {
        setStatus("写桥接区失败");
        return false;
    }

    u8 zero[0x60] = {};
    if (!poke(kScratch, zero, sizeof(zero))) {
        setStatus("清闩锁失败");
        return false;
    }

    // The borrowed string is the ceiling: kSlotPtr reads decimal.MaxValue, whose
    // buffer holds 29 UTF-16 units; gen_extra_items.py caps ids at 26.
    const u32 len = static_cast<u32>(std::strlen(id));
    if (len == 0 || len > sdv::kMaxIdLen) {
        setStatus("编号过长");
        logError("id string too long: %s", id);
        return false;
    }

    // Which string to borrow is a runtime question.  The offline slot table lists
    // addresses that *should* hold a MonoString, but v7.0 crashed the game on the
    // 29-unit candidate: the shell died on the dereference before it wrote
    // anything, which is what a stale pointer looks like.  A data abort inside
    // the game is not catchable, so vet the slot from out here first -- the
    // overlay can read the same memory safely and just say no.
    // The strings we borrow are not constants: they are caches the game fills in
    // as it runs.  On a fresh launch 0x0BB90280 reads back as a plausible-looking
    // pointer whose "length" is 2.9 billion, and an hour of play later the same
    // address holds "(O)434" again.  So probe both candidates, take the one whose
    // length actually matches, and if neither does, say so instead of arming --
    // an empty slot is a crash, not an error we can catch.
    // The chain is two dereferences, not one: 0x0BB90280 holds the address of a
    // table, and the table holds the string.  The shell has always done both
    // (`ldr x8,[x8]` then `ldr x19,[x8]`); v23's rewrite dropped the first, and
    // this probe only ever did one -- so it measured a table as if it were a
    // string, decided the capacity was garbage, and refused every give. That is
    // what "编号槽未就绪" was.
    struct Cand { u64 off; const char* name; };
    // The 29-unit candidate was rejected in v7.2-v7.7 because it "crashed" -- but
    // that crash was the missing dereference, not the slot: it was being written
    // into as if the table were a string.  With the chain right it is just another
    // candidate, and it is the only one that can hold "(F)SmallStackedElixirShelf".
    const Cand cands[] = { { sdv::kSlotProven, "prov" }, { sdv::kSlotShort, "short" },
                           { sdv::kSlotLong, "long" } };

    u64 slotOff = 0;
    for (const Cand& c : cands) {
        u64 table = 0, str = 0;
        u32 cap = 0;
        const bool ok = peek(c.off, &table, sizeof(table)) && table != 0 &&
                        peekAbs(table, &str, sizeof(str)) && str != 0 &&
                        peekAbs(str + 0x10, &cap, sizeof(cap));
        logLine("  slot %s %08llX table=%016llX str=%016llX len=%u need=%u",
                c.name, (unsigned long long)c.off, (unsigned long long)table,
                (unsigned long long)str, (unsigned)cap, (unsigned)len);
        if (ok && cap == len) { slotOff = c.off; break; }
        if (!slotOff && ok && cap >= len && cap <= 64) slotOff = c.off;
    }

    if (!slotOff) {
        setStatus("槽未就绪");
        logError("  refusing to arm: no borrowed string of %u chars is loaded", (unsigned)len);
        return false;
    }

    u8 block[0x60] = {};
    std::memcpy(block + 0x00, &kCmdMagic, 4);
    std::memcpy(block + 0x04, &len, 4);
    for (u32 i = 0; i < len; ++i)
        block[kCmdChars + i * 2] = static_cast<u8>(id[i]);   // UTF-16, ASCII only

    u32 slotArg = static_cast<u32>(slotOff);
    std::memcpy(block + 0x3C, &slotArg, 4);       // which string the shell borrows
    std::memcpy(block + kCmdAmount, &amount, 4);
    std::memcpy(block + kCmdQuality, &quality, 4);
    u32 armed = 1;
    std::memcpy(block + kStateOff, &armed, 4);

    if (!poke(kCmd, block, sizeof(block))) {
        setStatus("写命令块失败");
        return false;
    }

    // One write, then wait.  An earlier version re-posted the block when the
    // shell had not answered within a second - but the shell may already have
    // read it and be inside Create, so rewriting underneath it fed the game a
    // half-updated block.  That is the likely cause of the console locking up.
    // The retry existed to paper over a missing smInitialize(), which is fixed
    // properly in attach().
    for (int i = 0; i < 30; ++i) {
        svcSleepThread(100'000'000ULL);
        u32 state = 1;
        if (!peek(kCmd + kStateOff, &state, 4))
            break;
        if (state == 3) {
            // Carry the amount in the confirmation: with the quantity now set
            // from two different pages, "已给 木材" alone no longer answers the
            // question the player is actually asking.
            std::snprintf(gStatus, sizeof(gStatus), "已给 \u00d7%u", (unsigned)amount);
            logBuiltString(id);
            logLine("  ok state=3");
            return true;
        }
        if (state != 1)
            break;
    }

    // No answer, or the shell bailed out early.  Every guard path writes its
    // code to scratch+8 and does NOT touch the command block (only the normal
    // path stores the final state at +0x28), so the reason has to be read from
    // scratch -- otherwise a failure here is just "nothing happened" again.
    u32 guard = 0, raw = 0;
    peek(kScratch + 8, &guard, sizeof(guard));
    peek(kScratch + 4, &raw, sizeof(raw));
    logError("  no success: guard=%u raw=%08X (id=%s)", (unsigned)guard,
             (unsigned)raw, id);
    logBuiltString(id);

    if (guard == 5)      setStatus("建串失败");
    else if (guard == 8) setStatus("建物品失败");
    else if (guard == 7) setStatus("编号异常");
    else if (guard == 9) setStatus("命令块不对");
    else                 setStatus("再点一次");
    return false;
}


// One page per category.  Six hundred and eighty rows in a single list is
// unusable, and building every row up front is wasted work when only one
// category is ever on screen.
class ItemListGui : public tsl::Gui {
public:
    explicit ItemListGui(int cat) : mCat(cat) {}

    tsl::elm::Element* createUI() override {
        auto frame = new tsl::elm::OverlayFrame(sdv::kCategoryNames[mCat], gStatus);
        mFrame = frame;

        auto list = new tsl::elm::List();
        for (int i = 0; i < sdv::kItemCount; ++i) {
            if (sdv::kItems[i].cat != mCat) continue;
            const char* id = sdv::kItems[i].id;
            const char* name = sdv::kItems[i].name;
            const u8 cat = sdv::kItems[i].cat;
            // Only the extra registries get an id on the right: "(W)4" says it is
            // a weapon, and those ids restart at 0, so a bare number would be
            // ambiguous with the objects listed on other pages.
            auto* row = new tsl::elm::ListItem(name, cat >= 10 ? id : "");
            row->setClickListener([id, name, cat](u64 keys) {
                if (keys & HidNpadButton_A) {
                    giveItem(id, name, cat);
                    return true;
                }
                return false;
            });
            list->addItem(row);
        }

        frame->setContent(list);
        return frame;
    }

    void update() override {
        if (!mFrame) return;
        // Weapons / hats / clothing / furniture do not stack, so giveItem hands
        // over exactly one and ignores gAmount.  Without saying so, the "数量与品质
        // x10" row on the main menu looks like it should apply here too.
        if (mCat >= 10) {
            // These registries hold individual entries, so the quantity on the
            // main menu does not apply here.  Say so on the page itself rather
            // than letting the main menu imply otherwise.
            std::string s = "只加 1 个 · ";
            s += gStatus;
            mFrame->setSubtitle(s);
        } else {
            mFrame->setSubtitle(gStatus);
        }
    }

private:
    int mCat;
    tsl::elm::OverlayFrame* mFrame = nullptr;
};

// -------------------------------------------------------------------- search
