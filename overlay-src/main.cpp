// Stardew Valley item overlay for Tesla.
//
// Why this exists: the cheat-file route cannot carry the item list.  EdiZon
// loads at most 256 instruction lines, the shell itself needs 82 of them, and
// the user's own 28 sections take 128 more - leaving room for about four items.
// An overlay is a program, so it has no such budget: it writes the shell and
// the command block straight into the game's memory through dmnt:cht, which is
// the same channel the cheats use.
//
// The game-side contract is unchanged from the PC console: a command block at
// 0x0C964000 (magic, length, UTF-16 id, amount, quality, state) that the
// injected shell polls.  Nothing here depends on the cheat file at all.

