// How far a finger may travel and still count as a tap rather than a drag.
// libtesla itself flips to TouchScroll at ~31 px (it compares squared
// distances against 1000), so anything under this is just thumb wobble.
constexpr s32 kTapSlop = 48;

// The keyboard.  A plain Element rather than a List of buttons: thirty-nine
// rows in a scrolling list is the wrong shape for a keyboard, and grid
// navigation is four lines of arithmetic.
class Keypad : public tsl::elm::Element {
public:
    tsl::elm::Element* requestFocus(tsl::elm::Element*, tsl::FocusDirection) override {
        return this;
    }

    void layout(u16 parentX, u16 parentY, u16 parentWidth, u16 parentHeight) override {
        // Safety net: if anything ever hands us the raw canvas instead of the
        // frame's content box, re-apply the frame inset rather than drawing a
        // keyboard two thirds of the way off screen.  The real layout comes
        // from Switcher, which already holds the correct box.
        if (parentWidth >= tsl::cfg::FramebufferWidth &&
            parentHeight >= tsl::cfg::FramebufferHeight) {
            parentX      = static_cast<u16>(parentX + 35);
            parentY      = static_cast<u16>(parentY + 125);
            parentWidth  = static_cast<u16>(parentWidth - 85);
            parentHeight = static_cast<u16>(parentHeight - 198);
        }

        this->setBoundaries(parentX, parentY, parentWidth, parentHeight);
    }

    void draw(tsl::gfx::Renderer* renderer) override;
    bool handleInput(u64 keysDown, u64 keysHeld, const HidTouchState& touchPos,
                     HidAnalogStickState left, HidAnalogStickState right) override;
    bool onClick(u64 keys) override;
    bool onTouch(tsl::elm::TouchEvent event, s32 currX, s32 currY,
                 s32 prevX, s32 prevY, s32 initialX, s32 initialY) override;

    // The stock focus decoration is a full-size rectangle plus a pulsing
    // border, which would frame the entire keyboard.  The selected key already
    // shows where the cursor is.
    void drawFocusBackground(tsl::gfx::Renderer*) override { }
    void drawHighlight(tsl::gfx::Renderer*) override { }

private:
    struct Rect { s32 x, y, w, h; };

    void move(s32 dx, s32 dy);
    void activate(s32 idx);
    s32  rowLen(s32 row) const;
    s32  hitTest(s32 px, s32 py) const;

    s32  mKey      = 0;
    s32  mTouchKey = -1;      // key under the finger, -1 when nothing is held
    Rect mRect[64] = {};
};

// Two views, one Gui.  A second Gui would have to be pushed with changeTo(),
// which is one-way: there is no pop that is safe to call from an input
// callback, so B would never find its way back to the result list.
class Switcher : public tsl::elm::Element {
public:
    Switcher(tsl::elm::Element* results, tsl::elm::Element* keypad)
        : mResults(results), mKeypad(keypad) {
        mResults->setParent(this);
        mKeypad->setParent(this);
    }

    ~Switcher() override {
        delete mResults;
        delete mKeypad;
    }

    void setActive(int which) {
        if (mActive == which) return;
        mActive = which;

        // Re-lay against OUR OWN bounds, never via Element::invalidate().
        // invalidate() relays an element with its *parent's* bounds, and this
        // element's parent is the OverlayFrame -- whose bounds are the whole
        // screen (0,0,1280,720), not the inset content box OverlayFrame hands
        // its child in layout().  Going through invalidate() therefore dropped
        // the 35/125 inset: the keypad jumped to the top of the screen, ran
        // over the title bar and lost the bottom margin, which is exactly what
        // "键盘显示不全" looked like on hardware.
        this->layout(static_cast<u16>(this->getX()), static_cast<u16>(this->getY()),
                     static_cast<u16>(this->getWidth()), static_cast<u16>(this->getHeight()));
    }

    tsl::elm::Element* requestFocus(tsl::elm::Element* old, tsl::FocusDirection dir) override {
        return active()->requestFocus(old, dir);
    }

    void layout(u16 parentX, u16 parentY, u16 parentWidth, u16 parentHeight) override {
        // libtesla throws the content inset away before we ever see it.
        // OverlayFrame::layout() does
        //     content->setBoundaries(parentX + 35, parentY + 125, w - 85, h - 198);
        //     content->invalidate();
        // and invalidate() re-runs layout with ELEMENT_BOUNDS(parent), which is
        // the frame itself -- i.e. the whole 448x720 canvas, never the inset.
        // The only place the real box still exists is our own bounds, set by
        // that setBoundaries() a moment earlier, so when the incoming rect is
        // the full canvas and we already hold something smaller, keep ours.
        if (parentWidth >= tsl::cfg::FramebufferWidth &&
            parentHeight >= tsl::cfg::FramebufferHeight &&
            this->getWidth() > 0 && this->getHeight() > 0 &&
            (this->getWidth() < tsl::cfg::FramebufferWidth ||
             this->getHeight() < tsl::cfg::FramebufferHeight)) {
            parentX      = static_cast<u16>(this->getX());
            parentY      = static_cast<u16>(this->getY());
            parentWidth  = this->getWidth();
            parentHeight = this->getHeight();

            static bool logged = false;
            if (!logged) {
                logged = true;
                logLine("inset kept %d,%d %dx%d (canvas was %ux%u)",
                        (int)parentX, (int)parentY, (int)parentWidth, (int)parentHeight,
                        (unsigned)tsl::cfg::FramebufferWidth, (unsigned)tsl::cfg::FramebufferHeight);
            }
        }

        this->setBoundaries(parentX, parentY, parentWidth, parentHeight);

        // List does NOT set its own box: List::layout() only stacks its items
        // against this->getX()/getY()/getWidth(), and whoever installs the list
        // is expected to have called setBoundaries() first -- normally
        // OverlayFrame::setContent(), because the list is usually the frame's
        // direct child.  Here it is not: this Switcher is, and it never called
        // setBoundaries on the list, so the list stayed at its constructed 0x0.
        //
        // That is invisible-but-fatal rather than merely ugly: List::draw()
        // culls with getTopBound()/getBottomBound() (== 0,0), so every row
        // failed "entry->getTopBound() < this->getBottomBound()" and nothing was
        // drawn, and enableScissoring() got a zero-width rect for the same
        // reason.  The result page came up as a blank black box even though the
        // search had found 49 rows and the view switch had happened -- which is
        // what "搜索不到任何东西" was actually showing.
        mResults->setBoundaries(parentX, parentY, parentWidth, parentHeight);
        mResults->layout(parentX, parentY, parentWidth, parentHeight);

        // Keypad::layout() sets its own box, so it only needs the call.
        mKeypad->layout(parentX, parentY, parentWidth, parentHeight);
    }

    void draw(tsl::gfx::Renderer* renderer) override {
        active()->frame(renderer);
    }

    // Element::onTouch is a no-op, so without this the keypad never sees a
    // tap: OverlayFrame forwards to its content element (this Switcher) and
    // stops there.
    bool onTouch(tsl::elm::TouchEvent event, s32 currX, s32 currY,
                 s32 prevX, s32 prevY, s32 initialX, s32 initialY) override {
        return active()->onTouch(event, currX, currY, prevX, prevY, initialX, initialY);
    }

private:
    tsl::elm::Element* active() { return mActive ? mKeypad : mResults; }

    tsl::elm::Element* mResults;
    tsl::elm::Element* mKeypad;
    int mActive = 0;
};

class SearchGui : public tsl::Gui {
public:
    tsl::elm::Element* createUI() override;
    void update() override;
    bool handleInput(u64 keysDown, u64 keysHeld, const HidTouchState& touchPos,
                     HidAnalogStickState left, HidAnalogStickState right) override;

private:
    void buildRows();
    std::string subtitle() const;

    tsl::elm::OverlayFrame* mFrame = nullptr;
    tsl::elm::List* mList = nullptr;
    Switcher* mSwitch = nullptr;
    int mShown = 0;
    bool mLogNext = false;
    char mLastStatus[128] = "";   // last gStatus painted into the subtitle
};

tsl::elm::Element* SearchGui::createUI() {
    gWantKeypad = 0;
    mShown = 0;

    mFrame = new tsl::elm::OverlayFrame("搜索", subtitle());
    mList = new tsl::elm::List();
    mSwitch = new Switcher(mList, new Keypad());

    // The constructor above already used the current status, so seed the cache
    // with it: otherwise the first update() would repaint the same string.
    std::strncpy(mLastStatus, gStatus, sizeof(mLastStatus) - 1);
    mLastStatus[sizeof(mLastStatus) - 1] = '\0';

    buildRows();
    mFrame->setContent(mSwitch);
    return mFrame;
}

std::string SearchGui::subtitle() const {
    std::string s;
    if (gQuery[0]) {
        s = "关键字 ";
        s += gQuery;
    } else {
        s = "拼音首字母 / 英文 / 编号";
    }

    // Quantity and quality belong here because they are what L/R and Y change on
    // this page: a key that alters the next give with no on-screen feedback is
    // worse than no key at all.
    s += "  ";
    s += settingsText();

    // The frame subtitle is the only place this overlay reports "已给 xx", and
    // the result page kept overwriting it with the query alone: a tap that went
    // through and a tap that silently failed looked exactly the same here, while
    // on the category pages the item name showed up straight away.  Query first,
    // last result after it, so the page still says what it is searching for.
    if (gStatus[0]) {
        s += " · ";
        s += gStatus;
    }
    return s;
}

bool SearchGui::handleInput(u64 keysDown, u64, const HidTouchState&,
                            HidAnalogStickState, HidAnalogStickState) {
    // Result page only.  On the keyboard L/R move the cursor and Y is backspace,
    // and libtesla still calls Gui::handleInput() after the focused element has
    // already consumed the press -- so without this guard a backspace would also
    // walk the quality ladder.
    if (mShown) return false;

    if (handleSettingKeys(keysDown))
        mFrame->setSubtitle(subtitle());
    return false;
}

void SearchGui::update() {
    ++gTick;

    // One frame after every switch: what the list actually got.  A blank result
    // page is either "nothing matched" or "the list has no box to draw in", and
    // those two are indistinguishable on a photo of the screen.
    if (mLogNext) {
        mLogNext = false;
        tsl::elm::Element* a = mList->getItemAtIndex(0);
        tsl::elm::Element* b = mList->getItemAtIndex(1);
        logLine("list %d,%d %dx%d  i0 %d,%d %dx%d  i1 %d,%d",
                (int)mList->getX(), (int)mList->getY(),
                (int)mList->getWidth(), (int)mList->getHeight(),
                a ? (int)a->getX() : -1, a ? (int)a->getY() : -1,
                a ? (int)a->getWidth() : -1, a ? (int)a->getHeight() : -1,
                b ? (int)b->getX() : -1, b ? (int)b->getY() : -1);
    }

    // "已给 金枪鱼" has to appear here as promptly as it does on the category
    // pages, and those simply re-apply gStatus every frame.  Rebuilding the
    // subtitle only when the status text actually changed keeps that behaviour
    // without formatting a string 60 times a second, and it cannot swallow a
    // repeat give of the same item (the text is already correct then).
    if (std::strcmp(gStatus, mLastStatus) != 0) {
        std::strncpy(mLastStatus, gStatus, sizeof(mLastStatus) - 1);
        mLastStatus[sizeof(mLastStatus) - 1] = '\0';
        mFrame->setSubtitle(subtitle());
    }

    if (gWantKeypad == mShown) return;

    mShown = gWantKeypad;

    // Rebuild first, then switch, then re-focus -- in that order.
    //   * List::clear() only raises a flag; the rows are really deleted in the
    //     next draw().  Asking for focus before the rebuild therefore handed
    //     focus to a row that was about to be freed, and libtesla kept walking
    //     onClick() up from that dangling pointer for the rest of the frame.
    //   * restoreFocus() has to run after setActive(), or it requests focus from
    //     the view being left and the new one comes up with nothing selected.
    if (!mShown) buildRows();
    mSwitch->setActive(mShown);
    this->removeFocus();
    this->restoreFocus();
    mFrame->setSubtitle(subtitle());

    // The query changed, not the status: keep the cache in sync so the change
    // check above does not repaint what was just painted.
    std::strncpy(mLastStatus, gStatus, sizeof(mLastStatus) - 1);
    mLastStatus[sizeof(mLastStatus) - 1] = '\0';

    gSwitchTick = gTick;
    mLogNext    = !mShown;
    logLine("view=%s q=\"%s\" built=%d", mShown ? "keypad" : "results", gQuery,
            mShown ? 0 : 1);
}

void SearchGui::buildRows() {
    mList->clear();

    auto* box = new tsl::elm::ListItem("关键字", gQuery[0] ? gQuery : "未输入，按 A 输入");
    box->setClickListener([](u64 keys) {
        if (keys & HidNpadButton_A) {
            if (gTick - gSwitchTick < kClickGuardFrames) {
                logLine("row click dropped, %d frames after switch", gTick - gSwitchTick);
                return true;
            }
            gWantKeypad = 1;
            return true;
        }
        return false;
    });
    mList->addItem(box);

    if (!gQuery[0]) {
        // An empty query would otherwise list all 682 items, which is what the
        // category pages already do but slower to read.  Show the syntax.
        mList->addItem(new tsl::elm::CategoryHeader("怎么用"));
        mList->addItem(new tsl::elm::ListItem("jqy", "金枪鱼（拼音首字母）"));
        mList->addItem(new tsl::elm::ListItem("tuna", "金枪鱼（英文名）"));
        mList->addItem(new tsl::elm::ListItem("130", "编号 130"));
        return;
    }

    const int total = searchCount(gQuery);
    char head[64];
    if (total > kSearchLimit)
        std::snprintf(head, sizeof(head), "共 %d 条，显示前 %d 条", total, kSearchLimit);
    else
        std::snprintf(head, sizeof(head), "共 %d 条", total);
    mList->addItem(new tsl::elm::CategoryHeader(head));

    if (!total)
        mList->addItem(new tsl::elm::ListItem("没有匹配的物品", "换个关键词"));

    int shown = 0;
    for (int i = 0; i < sdv::kItemCount && shown < kSearchLimit; ++i) {
        if (!queryMatches(i, gQuery)) continue;
        ++shown;

        const char* id = sdv::kItems[i].id;
        const char* name = sdv::kItems[i].name;
        const u8 cat = sdv::kItems[i].cat;

        auto* row = new tsl::elm::ListItem(name, id);
        row->setClickListener([id, name, cat](u64 keys) {
            if (keys & HidNpadButton_A) {
                giveItem(id, name, cat);
                return true;
            }
            return false;
        });
        mList->addItem(row);
    }
}

s32 Keypad::rowLen(s32 row) const {
    const s32 remain = kKeyCount - row * kCols;
    if (remain <= 0) return 0;
    return remain < kCols ? remain : kCols;
}

void Keypad::move(s32 dx, s32 dy) {
    s32 row = mKey / kCols;
    s32 col = mKey % kCols;

    if (dx) {
        const s32 len = rowLen(row);
        col += dx;
        if (col < 0)
            col = len - 1;
        else if (col >= len)
            col = 0;
    }

    if (dy) {
        row += dy;
        if (row < 0)
            row = kRowCount - 1;
        else if (row >= kRowCount)
            row = 0;
        // The last row is short, so a column that exists above may not exist
        // below it.
        const s32 len = rowLen(row);
        if (col >= len) col = len - 1;
    }

    mKey = row * kCols + col;
}

bool Keypad::handleInput(u64 keysDown, u64, const HidTouchState&,
                         HidAnalogStickState, HidAnalogStickState) {
    if (keysDown & HidNpadButton_AnyLeft)  { move(-1, 0); return true; }
    if (keysDown & HidNpadButton_AnyRight) { move(1, 0);  return true; }
    if (keysDown & HidNpadButton_AnyUp)    { move(0, -1); return true; }
    if (keysDown & HidNpadButton_AnyDown)  { move(0, 1);  return true; }
    return false;
}

void Keypad::activate(s32 idx) {
    if (idx < 0 || idx >= kKeyCount) return;

    switch (kKeys[idx].kind) {
        case kKeyChar:   queryAppend(kKeys[idx].ch); break;
        case kKeyDelete: queryBackspace();           break;
        case kKeyClear:  queryClear();               break;
        // kKeyGo: leave the keyboard.  SearchGui::update() sees the flag flip
        // on the next frame, rebuilds the rows and swaps the view.
        default:         gWantKeypad = 0;            break;
    }

    // Only the action keys are logged.  Letters would flood the file, and it is
    // never the letters that misbehave -- if "搜索" is pressed and nothing
    // happens again, this line proves whether the press arrived at all.
    if (kKeys[idx].kind != kKeyChar)
        logLine("key '%s' pressed -> want=%d q=\"%s\" hits=%d",
                kKeys[idx].label, gWantKeypad, gQuery,
                (gQueryDirty ? searchCount(gQuery) : gQueryHits));
}

bool Keypad::onClick(u64 keys) {
    // B and + both go back to the result list; the list itself is left with B
    // so that a second press leaves the search page entirely.
    if (keys & (HidNpadButton_B | HidNpadButton_Plus)) {
        gWantKeypad = 0;
        return true;
    }
    if (keys & HidNpadButton_Y) {
        queryBackspace();
        return true;
    }
    if (keys & HidNpadButton_X) {
        queryClear();
        return true;
    }
    if (!(keys & HidNpadButton_A))
        return false;

    activate(mKey);
    return true;
}

s32 Keypad::hitTest(s32 px, s32 py) const {
    // Same rects draw() filled in, so what is on screen and what answers a tap
    // cannot drift apart.
    for (s32 i = 0; i < kKeyCount; ++i) {
        const Rect& r = mRect[i];
        if (r.w <= 0) continue;
        if (px >= r.x && px < r.x + r.w && py >= r.y && py < r.y + r.h)
            return i;
    }
    return -1;
}

bool Keypad::onTouch(tsl::elm::TouchEvent event, s32 currX, s32 currY,
                     s32, s32, s32 initX, s32 initY) {
    // libtesla hands out raw panel coordinates, and on this framebuffer size
    // one framebuffer pixel is one panel pixel, so no rescaling is needed.
    const s32 hit = hitTest(currX, currY);

    switch (event) {
        case tsl::elm::TouchEvent::Touch: {
            mTouchKey = hit;
            if (hit >= 0) mKey = hit;   // the d-pad continues from here
            // Once per run: the raw coordinate the pad reports next to the box
            // we are comparing it against.  If a tap ever lands on the wrong
            // key again, these two numbers say immediately whether it is a
            // scaling problem or a layout one.
            static bool logged = false;
            if (!logged) {
                logged = true;
                logLine("touch %d,%d inside %d,%d %dx%d -> key %d",
                        (int)currX, (int)currY, (int)this->getX(), (int)this->getY(),
                        (int)this->getWidth(), (int)this->getHeight(), (int)hit);
            }
            return hit >= 0;
        }

        case tsl::elm::TouchEvent::Hold:
            // Deliberately does not touch mTouchKey.  libtesla turns the input
            // mode into TouchScroll after ~31 px of movement, and a thumb on a
            // 55 px key routinely moves that much during a normal tap.  The
            // down-key is what decides the press; Release applies the slop.
            return hit >= 0;

        case tsl::elm::TouchEvent::Scroll:
            // Neither cancels here.  A deliberate swipe fails the slop test on
            // release; a jittery tap must still register.
            return false;

        case tsl::elm::TouchEvent::Release: {
            // Fire on the key the finger went *down* on, as long as it did not
            // travel far.  Requiring the release point to hit the very same
            // key is what made a normal tap on "搜索" do nothing: the pad
            // reports the last position with a couple of pixels of drift, and
            // one pixel past the edge silently swallowed the whole press.
            const s32 which = mTouchKey;
            mTouchKey = -1;
            if (which < 0) return false;

            const s32 dx = currX > initX ? currX - initX : initX - currX;
            const s32 dy = currY > initY ? currY - initY : initY - currY;
            if (dx > kTapSlop || dy > kTapSlop) {
                logLine("tap dropped: moved %d,%d from the press point", (int)dx, (int)dy);
                return false;
            }

            activate(which);
            return true;
        }

        default:
            return false;
    }
}

void Keypad::draw(tsl::gfx::Renderer* renderer) {
    const s32 x = this->getX();
    const s32 y = this->getY();
    const s32 w = this->getWidth();
    const s32 h = this->getHeight();

    // Everything is derived from the box libtesla actually handed over.
    // OverlayFrame insets its child to (35, 125, 448-85, 720-198), i.e. a
    // 363x522 box -- the drawing space is 448x720, not the 1280x720 of the
    // panel, which is what made the first two attempts lay out twice too wide.
    constexpr s32 kPad     = 4;
    constexpr s32 kGap     = 4;
    constexpr s32 kQueryH  = 40;
    constexpr s32 kFooterH = 18;

    const s32 innerW = w - 2 * kPad;

    s32 cellW = (innerW - (kCols - 1) * kGap) / kCols;
    if (cellW < 16) cellW = 16;

    s32 keyH = (h - kQueryH - kFooterH - 2 * kGap - (kRowCount - 1) * kGap) / kRowCount;
    if (keyH < 18) keyH = 18;

    const s32 gridH = kRowCount * keyH + (kRowCount - 1) * kGap;
    const s32 slack = h - kQueryH - kFooterH - 2 * kGap - gridH;
    const s32 top   = y + kQueryH + kGap + (slack > 0 ? slack / 2 : 0);

    static s32 loggedW = -1, loggedH = -1;
    if (w != loggedW || h != loggedH) {
        loggedW = w; loggedH = h;
        logLine("keypad x=%d y=%d w=%d h=%d key=%d cell=%d rows=%d",
                (int)x, (int)y, (int)w, (int)h, (int)keyH, (int)cellW, (int)kRowCount);
    }

    // Query field.  No caret until there is text: a blinking bar behind the
    // placeholder reads as a rendering fault.
    refreshQueryHits();

    renderer->drawRect(x + kPad, y, innerW, kQueryH, fade(tsl::Color(0x1, 0x1, 0x1, 0xF)));
    if (gQuery[0]) {
        const auto measure = renderer->drawString(gQuery, false, 0, 0, 24,
                                                  tsl::style::color::ColorTransparent);
        renderer->drawString(gQuery, false, x + kPad + 10, y + 28, 24,
                             fade(tsl::style::color::ColorText));
        renderer->drawRect(x + kPad + 14 + static_cast<s32>(measure.first), y + 8, 2, 24,
                           fade(tsl::style::color::ColorHighlight));

        // Hit count on the right of the field: immediate feedback while typing,
        // instead of finding out only after leaving the keyboard.
        char hits[24];
        if (gQueryHits > 0)
            std::snprintf(hits, sizeof(hits), "%d 条", gQueryHits);
        else
            std::snprintf(hits, sizeof(hits), "无匹配");

        const auto hm = renderer->drawString(hits, false, 0, 0, 16,
                                             tsl::style::color::ColorTransparent);
        renderer->drawString(hits, false,
                             x + w - kPad - 8 - static_cast<s32>(hm.first), y + 27, 16,
                             fade(gQueryHits ? tsl::style::color::ColorHighlight
                                             : tsl::style::color::ColorDescription));
    } else {
        renderer->drawString("拼音首字母 / 英文 / 编号", false, x + kPad + 10, y + 27, 17,
                             fade(tsl::style::color::ColorDescription));
    }

    for (s32 row = 0; row < kRowCount; ++row) {
        const s32 n     = rowLen(row);
        const s32 total = n * cellW + (n - 1) * kGap;
        const s32 left  = x + (w - total) / 2;

        for (s32 col = 0; col < n; ++col) {
            const s32 idx  = row * kCols + col;
            const s32 keyX = left + col * (cellW + kGap);
            const s32 keyY = top + row * (keyH + kGap);

            mRect[idx] = { keyX, keyY, cellW, keyH };

            const bool focus   = (idx == mKey);
            const bool pressed = (idx == mTouchKey);

            renderer->drawRect(keyX, keyY, cellW, keyH,
                               fade(pressed ? tsl::style::color::ColorText
                                            : (focus ? tsl::style::color::ColorHighlight
                                                     : tsl::Color(0x3, 0x3, 0x3, 0xF))));

            const char* label = kKeys[idx].label;
            const s32   size  = (kKeys[idx].kind == kKeyChar) ? 24 : 20;
            const auto  measure = renderer->drawString(label, false, 0, 0, size,
                                                       tsl::style::color::ColorTransparent);

            renderer->drawString(label, false,
                                 keyX + (cellW - static_cast<s32>(measure.first)) / 2,
                                 keyY + keyH / 2 + size / 2 - 2, size,
                                 fade((focus || pressed) ? tsl::Color(0x0, 0x0, 0x0, 0xF)
                                                         : tsl::style::color::ColorText));
        }
    }

    renderer->drawString("触屏点按 / A 输入 / B 返回", false,
                         x + kPad, y + h - 4, 14,
                         fade(tsl::style::color::ColorDescription));
}

