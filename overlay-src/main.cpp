// Dump the module that keeps showing up in crash reports but is not ours.
//
// Every crash report so far places rtld at a fixed distance from the game's own
// base, six reports out of six:
//
//     rtld = main - 0x006000
//
// so it can be read out of the live process without any symbol lookup.  Having
// rtld offline is the point: the fault is always at rtld+0x2238, and that
// instruction has been guessed at for six rounds because the only rtld on disk
// is from a different game build.
//
// saltysd_core was dumped the same way, at main - 0x2006000, and that guess
// failed on every run since it was added: read error at the first byte, and
// until v1.0.4 an empty file left behind to look like a success.
//
// The memory map says why.  main - 0x2006000 is unmapped in the live process --
// there is nothing there to read.  The module sits one order of magnitude
// closer, at main - 0x206000, and has since the first run: 0x1C000 bytes of
// r-x followed by rodata and data, ending at main - 0x6000 where rtld begins.
// The old number was off by a single zero, and kSaltySize was 0x1C000 all
// along -- the size was right and the delta was wrong, which is why the failure
// looked like "the module is gone" rather than "the address is wrong".
//
// The map stays part of the export: it is what turned this up, and it is what
// makes the next such question answerable without another build.
//
// Read in small chunks -- a single multi-KB dmntcht read is unreliable, and a
// partial dump is worse than none.
constexpr u64 kRtldDelta    = 0x006000;
constexpr u64 kRtldSize     = 0x003000;
constexpr u64 kSaltyDelta   = 0x206000;
constexpr u64 kSaltySize    = 0x01C000;
constexpr const char* kMapPath = "sdmc:/sdv_map.txt";

bool peekAbs(u64 addr, void* out, size_t size);
bool attach();

// Defined next to the patch offsets; called from dumpRuntime() up here, which is
// why it needs a forward declaration.
void checkToggleConsistency();

bool dumpRange(const char* path, u64 addr, u64 size) {
    if (!gFsMounted) {
        fsdevMountSdmc();
        gFsMounted = true;
    }
    FILE* f = std::fopen(path, "wb");
    if (!f) {
        logError("dump: cannot open %s", path);
        return false;
    }

    u8 buf[0x400];
    u64 done = 0;
    while (done < size) {
        const u64 n = (size - done) < sizeof(buf) ? (size - done) : sizeof(buf);
        if (!peekAbs(addr + done, buf, n)) {
            logError("dump: read failed at %s+%llX", path, (unsigned long long)done);
            std::fclose(f);
            // Do not leave a half-written or empty file behind.  A zero-byte
            // sdv_salty.bin sits next to a good sdv_rtld.bin and looks exactly
            // like a successful export of nothing, so it gets sent anyway and
            // the reader wastes a round trip on it.  Missing is unambiguous.
            std::remove(path);
            return false;
        }
        std::fwrite(buf, 1, n, f);
        done += n;
    }
    std::fclose(f);
    logLine("dump: %s  %llX bytes from %llX", path, (unsigned long long)size,
            (unsigned long long)addr);
    return true;
}

// The process's memory map, one line per region.  This replaces a fixed-distance
// guess at where saltysd_core lives: the map is read from the kernel, so it says
// where everything actually is.  A crash report names a module and an offset;
// with the bases in this file that becomes an address, and an address becomes a
// region with a type -- enough to tell a code fault in a sysmodule from a heap
// or stack fault without asking the reporter for anything else.
//
// Written in chunks of 32 regions rather than one big buffer: the count is
// reported separately, and a game process runs to a few hundred mappings.
bool dumpMemoryMap(u64 pid) {
    if (!gFsMounted) {
        fsdevMountSdmc();
        gFsMounted = true;
    }
    FILE* f = std::fopen(kMapPath, "w");
    if (!f) {
        logError("map: cannot open %s", kMapPath);
        return false;
    }

    std::fprintf(f, "# game process memory map\n");
    std::fprintf(f, "pid     %llu\n", (unsigned long long)pid);
    std::fprintf(f, "main    %016llX  size %llX\n",
                 (unsigned long long)gNsoBase, (unsigned long long)gNsoSize);
    std::fprintf(f, "rtld    %016llX  (main - 6000, dumped to sdv_rtld.bin)\n",
                 (unsigned long long)(gNsoBase - kRtldDelta));
    std::fprintf(f, "#\n# base              size        perm  type  note\n");

    u64 total = 0;
    if (R_FAILED(dmntchtGetCheatProcessMappingCount(&total))) {
        std::fprintf(f, "# mapping count unavailable\n");
        logError("map: mapping count read failed");
        std::fclose(f);
        return false;
    }

    MemoryInfo chunk[32];
    u64 off = 0;
    u64 written = 0;
    while (off < total) {
        u64 got = 0;
        if (R_FAILED(dmntchtGetCheatProcessMappings(chunk, 32, off, &got)) || got == 0)
            break;
        for (u64 i = 0; i < got; i++) {
            const MemoryInfo& m = chunk[i];
            char perm[4] = { '-', '-', '-', 0 };
            if (m.perm & Perm_R) perm[0] = 'r';
            if (m.perm & Perm_W) perm[1] = 'w';
            if (m.perm & Perm_X) perm[2] = 'x';

            // Mark the two regions that matter to us rather than making the
            // reader do the subtraction by eye.
            const char* note = "";
            if (m.addr == gNsoBase)                       note = "main";
            else if (m.addr == gNsoBase - kRtldDelta)     note = "rtld";
            else if (m.addr == gNsoBase - kSaltyDelta)    note = "saltysd";

            std::fprintf(f, "%016llX  %010llX  %s  %02X    %s\n",
                         (unsigned long long)m.addr,
                         (unsigned long long)m.size, perm,
                         (unsigned)m.type, note);
            written++;
        }
        off += got;
    }

    std::fprintf(f, "#\n# %llu of %llu regions written\n",
                 (unsigned long long)written, (unsigned long long)total);
    std::fclose(f);
    logLine("map: %s  %llu/%llu regions", kMapPath,
            (unsigned long long)written, (unsigned long long)total);
    return written > 0;
}

void dumpRuntime() {
    if (!attach()) return;

    const u64 rtld  = gNsoBase - kRtldDelta;
    const u64 salty = gNsoBase - kSaltyDelta;

    // Identification, not decoration: the delta is still a constant, and if a
    // future Atmosphere moves the module again this is the line that says
    // whether we dumped a module header or a hole.
    //
    // It is not an NSO header, and checking for one was the wrong test: a
    // homebrew module injected by rtld starts with a branch, a module offset,
    // and the magic "HOMEBREW" at +8.  The export contains exactly that --
    // 14000020 / 00000130 / "HOME" "BREW" -- so the magic lives in words 2 and
    // 3, not 1 and 2.  Build 7 read three words and compared the wrong pair,
    // which is why a good dump still printed "unknown header".
    u32 hdr[4] = { 0, 0, 0, 0 };
    if (peekAbs(salty, hdr, sizeof(hdr))) {
        if (hdr[0] == 0x304F534E)                       // "NSO0"
            logLine("saltysd: NSO0 header %08X %08X %08X",
                    (unsigned)hdr[0], (unsigned)hdr[1], (unsigned)hdr[2]);
        else if (hdr[2] == 0x454D4F48 && hdr[3] == 0x57455242)  // "HOMEBREW"
            logLine("saltysd: HOMEBREW module, mod offset %X",
                    (unsigned)hdr[1]);
        else
            logLine("saltysd: first words %08X %08X %08X %08X (unknown header)",
                    (unsigned)hdr[0], (unsigned)hdr[1], (unsigned)hdr[2],
                    (unsigned)hdr[3]);
    }

    const bool a = dumpRange("sdmc:/sdv_rtld.bin",  rtld,  kRtldSize);
    const bool c = dumpRange("sdmc:/sdv_salty.bin", salty, kSaltySize);
    const bool b = dumpMemoryMap(gPid);

    // Nothing longer than fits next to the title: the subtitle is a single
    // right-aligned line, and a 13-character message runs straight into it.
    // Which file failed is in the log, one line each.
    if (a && b)      setStatus(c ? "已导出" : "导出不完整");
    else             setStatus("导出失败");

    // A diagnostic export is the moment someone is about to send this file in,
    // so it is also the right moment to say whether the switches on screen match
    // what is actually patched.  Costs six reads.
    if (gOpen) checkToggleConsistency();
}




